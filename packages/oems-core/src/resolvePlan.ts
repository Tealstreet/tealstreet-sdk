import type { OemsContext, OemsMarketRef, OemsOrderRef, OemsPositionRef } from './context.types';
import type { OemsIntent, OemsIntentKind, OemsOrderScope, OemsPlan, OemsPositionScope } from './intent.types';
import type { OemsWriteMethod } from './surface';

import { roundCloseSize, roundToStep } from '@tealstreet/script-api-core/src/order/rounding';

/**
 * The deterministic half.
 *
 * A plan says WHAT the user asked for; this turns it into the exact calls that
 * would be made, or says why it cannot. Everything here is pure — the context
 * is the only input — so the confirm card the user sees is generated by code
 * that can be tested rather than by the model that wrote the sentence.
 *
 * ## Rejections are output, not exceptions
 *
 * A plan touching five positions where one account is still connecting should
 * do the other four and say so. Throwing would either lose the four or force
 * the caller to re-run the resolution, and a partial resolution is exactly
 * what the confirm step is for.
 *
 * ## The args are the SDK adapter's, positionally
 *
 * Every `args` array is shaped for a method of `AdapterContext` in
 * `packages/script-api-core/src/adapter/` — the same boundary custom scripts,
 * hotkeys and the CLI go through. The host re-validates everything here and
 * re-resolves every address against live state; this resolver exists to make a
 * REFUSAL legible before the user confirms, never to replace that check.
 */

/** Several venues cancel one round-trip per order, so a batch is chunked
 *  rather than sent whole — cancelling forty orders arrives as two calls. */
const MAX_CANCEL_BATCH = 25;

/** Refuses the obviously-wrong rather than claiming to know each venue's real
 *  maximum. */
const MAX_LEVERAGE = 1_000;

/**
 * How old a snapshot may be and still be resolvable.
 *
 * The whole plan is refused rather than resolved against a stale book: the
 * user confirms what this produces, and "reduce by 30%" resolved against
 * minute-old sizes is a wrong number wearing a confirm button. Re-asking is
 * cheap; a wrong close is not.
 */
const DEFAULT_MAX_CONTEXT_AGE_MS = 30_000;

/**
 * One number the USER typed over the one this resolver derived.
 *
 * ## Why it enters HERE rather than patching the output
 *
 * The obvious shape is to resolve normally and then patch `command.args`. It
 * does not survive contact with this file. `args[0]` is an options bag only
 * for `placeOrder` — `cancelOrders` and `updateOrder` put an order ID there
 * and `setLeverage` a symbol, so a blind patch corrupts them — and the linear
 * `closePosition` fast path deliberately carries NO amount so the host can
 * read a size newer than this snapshot.
 *
 * The deeper problem is that every check that makes a size safe lives in this
 * module: `minAmount` / `maxAmount`, the `Math.min(…, full)` clamp that stops
 * a close exceeding its position, and `fatFingerNotional`. Fat-finger in
 * particular is enforced NOWHERE else on this path — `prepareOrder` excludes
 * it by design, and the Agent never calls the web `createLimitOrder` that has
 * it. A patched-afterwards amount would reach a venue with the user's own
 * limit unchecked.
 *
 * So an override replaces the number BEFORE resolution continues, and every
 * check re-runs against it exactly as it would against a derived one. The
 * preview is written afterwards, so it always states the number that will
 * actually be sent rather than a substituted one.
 *
 * ## Identity is the order, not its position in a list
 *
 * Keyed by `symbol` + `account` + `side` because two positions both resolve to
 * `placeOrder`, and `context.positions` has no guaranteed order — an index
 * would silently map a user's edit onto a different account's order.
 */
export interface OemsOverride {
  /**
   * The `plan.steps` index this edit belongs to.
   *
   * Symbol + account + side alone is NOT an identity. One plan can carry a
   * reduce and a stop on the same symbol, same account, same side — editing
   * the reduce would silently rewrite the stop's size too and leave the rest
   * of the position unprotected. A ladder of two buys on one symbol has the
   * same problem. The step pins which row was edited; the three fields below
   * then pick one command out of a step that produced several.
   */
  readonly step: number;
  readonly symbol: string;
  readonly account: string;
  /** The ORDER's side, which for a close is the opposite of the position's. */
  readonly side: 'buy' | 'sell';
  readonly amount?: number;
  readonly price?: number;
}

export interface ResolveOptions {
  /** Injected so the resolver stays pure and testable. */
  readonly now?: number;
  readonly maxContextAgeMs?: number;
  /** User edits to apply before the safety checks — see `OemsOverride`. */
  readonly overrides?: readonly OemsOverride[];
}

export interface OemsCommand {
  /**
   * A method of the shared SDK's `AdapterContext`, and `args` are its
   * arguments positionally. Not a bespoke verb: the executor hands these
   * straight to the same adapter custom scripts and the CLI run on, so a
   * command that is not expressible there is a command this resolver must not
   * produce.
   */
  readonly method: OemsWriteMethod;
  readonly args: readonly unknown[];
  /** One line for the confirm card, in the user's own terms. */
  readonly preview: string;
  /** Which of `plan.steps` produced this, so an edit can name one row. Stamped
   *  by `resolveOemsPlan`; the step resolvers do not know their own index. */
  readonly step: number;
  /**
   * The fields a confirm card needs to render this as a row and to send an
   * edit back — present only when the row is genuinely overridable.
   *
   * The alternative is a view that casts `args[0]` to dig out the symbol and
   * side. That works until it does not: `args[0]` is an options bag for
   * `placeOrder` and an order id for a cancel, and a view reverse-engineering
   * the resolver's output is the drift this package exists to prevent. The
   * resolver has these values in hand when it builds the command.
   *
   * ABSENT means "no edit affordance". A cancel, an amend and a leverage
   * change carry none, and neither does a close the resolver would refuse to
   * edit — offering a pencil that can only ever produce a rejection is worse
   * than offering none.
   */
  readonly editable?: {
    readonly symbol: string;
    readonly account: string;
    /** The ORDER's side. A long's close is a `sell`. */
    readonly side: 'buy' | 'sell';
    readonly amount: number;
    /** Absent on a market order, which takes no price. */
    readonly price?: number;
  };
}

export interface OemsRejection {
  /** Index into `plan.steps`, so the widget can show which ask failed. */
  readonly step: number;
  readonly kind: OemsIntentKind;
  readonly reason: string;
}

export interface OemsResolution {
  readonly commands: readonly OemsCommand[];
  readonly rejections: readonly OemsRejection[];
}

const upper = (value: string): string => value.toUpperCase();

/** Symbols match case-insensitively because the host's own market lookup
 *  upper-cases before comparing. */
const inList = (list: readonly string[] | undefined, value: string): boolean =>
  !list || list.length === 0 || list.some((entry) => upper(entry) === upper(value));

/** The override for one order, if the user edited it. Symbol and account
 *  compare case-insensitively like every other match in this file. */
/**
 * An override is user input and gets the same scrutiny `parseOemsPlan` gives
 * the model's — it never passes through that parser, so nothing else checks it.
 *
 * `Infinity` is the case that matters. `roundToStep(Infinity)` is `Infinity`,
 * `Infinity > 0` is true, and `limitsComparable` is false on any market whose
 * `contractSize` is not 1 — so on an OKX-shaped market an infinite amount
 * cleared every downstream guard and reached the venue. Refusing it here means
 * one check rather than one per call site.
 */
const usableNumber = (value: number | undefined): boolean =>
  value === undefined || (Number.isFinite(value) && value > 0);

const overrideFor = (
  overrides: readonly OemsOverride[] | undefined,
  target: { step: number; symbol: string; account: string; side: 'buy' | 'sell' },
): OemsOverride | undefined => {
  const found = overrides?.find(
    (entry) =>
      entry.step === target.step &&
      upper(entry.symbol) === upper(target.symbol) &&
      upper(entry.account) === upper(target.account) &&
      entry.side === target.side,
  );
  if (!found) return undefined;
  if (!usableNumber(found.amount) || !usableNumber(found.price)) return undefined;
  return found;
};

/** The side an order closing this position takes. */
const closeSideOf = (position: OemsPositionRef): 'buy' | 'sell' => (position.side === 'long' ? 'sell' : 'buy');

const trim = (value: number): string => {
  const fixed = value.toFixed(8);
  return fixed.includes('.') ? fixed.replace(/0+$/, '').replace(/[.]$/, '') : fixed;
};

interface Lookups {
  readonly marketFor: (account: string, symbol: string) => OemsMarketRef | undefined;
  readonly accountProblem: (account: string) => string | undefined;
}

const buildLookups = (context: OemsContext): Lookups => {
  const markets = new Map<string, OemsMarketRef>();
  for (const market of context.markets) markets.set(`${market.account} ${upper(market.symbol)}`, market);

  const accounts = new Map(context.accounts.map((account) => [account.name, account]));

  return {
    marketFor: (account, symbol) => markets.get(`${account} ${upper(symbol)}`),
    accountProblem: (name) => {
      const account = accounts.get(name);
      if (!account) return `no account named "${name}"`;
      if (!account.active) return `account "${name}" is switched off`;
      if (!account.connected) return `account "${name}" is not connected yet`;
      return undefined;
    },
  };
};

const matchPositions = (context: OemsContext, scope: OemsPositionScope): OemsPositionRef[] =>
  context.positions.filter(
    (position) =>
      inList(scope.accounts, position.account) &&
      inList(scope.symbols, position.symbol) &&
      (scope.side === undefined || scope.side === position.side),
  );

const matchOrders = (context: OemsContext, scope: OemsOrderScope): OemsOrderRef[] =>
  context.orders.filter(
    (order) =>
      inList(scope.accounts, order.account) &&
      inList(scope.symbols, order.symbol) &&
      (scope.side === undefined || scope.side === order.side) &&
      (scope.reduceOnly === undefined || scope.reduceOnly === order.reduceOnly),
  );

/** A step resolver does not know its own index, so it emits commands WITHOUT
 *  `step` and `resolveOemsPlan` stamps it on the way out. */
type UnstampedCommand = Omit<OemsCommand, 'step'>;

interface StepOutput {
  commands: UnstampedCommand[];
  reasons: string[];
}

const empty = (): StepOutput => ({ commands: [], reasons: [] });

const noMarket = (symbol: string, account: string): string =>
  `no market data for ${symbol} on ${account} — the account may still be loading`;

/**
 * Whether a size in native units can be compared against `minAmount` /
 * `maxAmount` at all.
 *
 * `precision.amount` is native everywhere. `limits.amount` is NOT, and it is
 * not consistently anything: OKX and BloFin build `min` as `minSz × ctVal`
 * (base, or quote on an inverse market) while their `max` stays native
 * contracts; KuCoin, BitMEX and Crypto.com report both in native contracts
 * despite setting a `contractSize`. There is no conversion that is right for
 * all of them, and a wrong one refuses every order on a whole venue.
 *
 * So the check runs only where the two units provably coincide —
 * `contractSize === 1`, which is the overwhelming majority of markets — and is
 * skipped elsewhere. The host and the venue still reject an undersized order;
 * what is lost is the nicer pre-confirm message, and that is the right thing to
 * lose rather than guess.
 */
const limitsComparable = (market: OemsMarketRef): boolean => (market.contractSize || 1) === 1;

/**
 * Sizing a close, in the venue's OWN units.
 *
 * ## Why not `closePosition` with a `contracts` field
 *
 * That is the obvious shape and it is wrong on two whole venue classes.
 * `createMarketOrder`'s `amount` is NATIVE; `ModuleAPI.closePosition` passes
 * `Math.abs(position.contracts)`, which is base. The mismatch is
 * `contractSize`, and it goes BOTH ways — over-sending above 1 (where
 * reduce-only clamps and hides it) and under-sending below 1, where OKX's
 * `contractSize 0.01` markets would close a hundredth of the position and
 * report success. The card would say "close 0.05 BTC" and the position would
 * still be open.
 *
 * So a size is derived from `position.nativeContracts` — the number the
 * producer computed the way `getPositionNativeContracts` does — and sent as
 * `placeOrder({ type: 'market', amount, reduceOnly: true }, account)`, which is
 * exactly what
 * `closePosition` does internally, minus the unit confusion. `amountStep` is
 * native too, so the rounding finally lines up with it — `minAmount` is not,
 * which is what `limitsComparable` is about.
 *
 * The size is an UPPER bound rather than a promise: with
 * `metadata.autoDownSizeReduceOrders` set, `downSizeReduceOrder` shrinks a
 * reduce-only order further against resting ones. And `reduceOnly` is what
 * makes a stale snapshot safe — the venue can only close less than asked,
 * never open or flip.
 */
const sizeClose = (
  position: OemsPositionRef,
  fraction: number,
  market: OemsMarketRef | undefined,
  /** A size the user typed, replacing the derived `full * fraction`. It is
   *  still rounded, still clamped to the position, and still held to
   *  `minAmount` — an override changes the number, never the checks. */
  overrideAmount?: number,
): { amount: number } | { reason: string } => {
  if (!market) return { reason: noMarket(position.symbol, position.account) };

  const full = Math.abs(position.nativeContracts);
  if (!(full > 0)) {
    return { reason: `the ${position.symbol} position on ${position.account} has no size to close` };
  }

  const requested = overrideAmount !== undefined ? overrideAmount : full * fraction;
  if (!(requested > 0)) {
    return { reason: `${trim(requested)} is not a size to close on ${position.account}` };
  }

  // `roundCloseSize` falls back to the raw size rather than returning zero, and
  // `full` is already positive, so the result cannot be zero here.
  const rounded = Math.min(roundCloseSize(requested, market.amountStep), full);
  if (limitsComparable(market) && market.minAmount > 0 && rounded < market.minAmount) {
    return {
      reason: `${trim(rounded)} ${position.symbol} is below the ${trim(market.minAmount)} minimum on ${position.account}`,
    };
  }
  return { amount: rounded };
};

/** A close is the opposite side of the position it reduces. */
const closeCommand = (position: OemsPositionRef, amount: number, preview: string): UnstampedCommand => ({
  // No `price`: a close is a market order, and the resolver refuses a price
  // typed onto one — so it must not advertise the field either.
  //
  // And nothing at all on a HEDGED position. A bare reduce-only order cannot
  // name a leg, which is why the linear fast path refuses an edit; an inverse
  // or contract-sized hedge reaches here instead, with the same hazard and no
  // guard in front of it. Offering no pencil is the consistent answer.
  ...(position.positionMode === 'hedged'
    ? {}
    : {
        editable: {
          symbol: position.symbol,
          account: position.account,
          side: closeSideOf(position),
          amount,
        },
      }),
  method: 'placeOrder',
  args: [
    {
      symbol: position.symbol,
      side: position.side === 'long' ? 'sell' : 'buy',
      type: 'market',
      amount,
      reduceOnly: true,
    },
    position.account,
  ],
  preview,
});

const resolveReduce = (
  context: OemsContext,
  lookups: Lookups,
  step: Extract<OemsIntent, { kind: 'reduce_positions' }>,
  stepIndex: number,
  overrides?: readonly OemsOverride[],
): StepOutput => {
  const out = empty();
  if (!(step.percent > 0) || step.percent >= 100) {
    out.reasons.push(`percent must be between 0 and 100 — a full close is close_positions (got ${step.percent})`);
    return out;
  }

  const positions = matchPositions(context, step.scope);
  if (positions.length === 0) {
    out.reasons.push('no open positions match that description');
    return out;
  }

  for (const position of positions) {
    const problem = lookups.accountProblem(position.account);
    if (problem) {
      out.reasons.push(problem);
      continue;
    }
    const edit = overrideFor(overrides, {
      step: stepIndex,
      symbol: position.symbol,
      account: position.account,
      side: closeSideOf(position),
    });
    if (edit?.price !== undefined) {
      out.reasons.push(`a ${position.symbol} reduce on ${position.account} is a market order — it takes no price`);
      continue;
    }
    const sized = sizeClose(
      position,
      step.percent / 100,
      lookups.marketFor(position.account, position.symbol),
      edit?.amount,
    );
    if ('reason' in sized) {
      out.reasons.push(sized.reason);
      continue;
    }
    out.commands.push(
      closeCommand(
        position,
        sized.amount,
        // An edited size is no longer a percentage of anything, so the
        // preview drops the "(30%)" clause rather than stating a percentage
        // the number no longer matches.
        edit?.amount !== undefined
          ? `Reduce ${position.symbol} ${position.side} on ${position.account} by ` +
            `${trim(sized.amount)} of ${trim(Math.abs(position.nativeContracts))}`
          : `Reduce ${position.symbol} ${position.side} on ${position.account} by ` +
            `${trim(sized.amount)} of ${trim(Math.abs(position.nativeContracts))} (${step.percent}%)`,
      ),
    );
  }
  return out;
};

const resolveClose = (
  context: OemsContext,
  lookups: Lookups,
  step: Extract<OemsIntent, { kind: 'close_positions' }>,
  stepIndex: number,
  overrides?: readonly OemsOverride[],
): StepOutput => {
  const out = empty();
  const positions = matchPositions(context, step.scope);
  if (positions.length === 0) {
    out.reasons.push('no open positions match that description');
    return out;
  }

  for (const position of positions) {
    const problem = lookups.accountProblem(position.account);
    if (problem) {
      out.reasons.push(problem);
      continue;
    }
    const market = lookups.marketFor(position.account, position.symbol);
    /**
     * A plain linear market is the one case where `closePosition` is both
     * correct and BETTER: `contracts` and native agree, and naming the address
     * lets the host read a size newer than this snapshot. Everywhere else the
     * base/native mismatch makes it wrong in one direction or the other, so the
     * size is computed here instead.
     */
    const edit = overrideFor(overrides, {
      step: stepIndex,
      symbol: position.symbol,
      account: position.account,
      side: closeSideOf(position),
    });
    const fastPathFits = Boolean(market && !market.isInverse && (market.contractSize || 1) === 1);
    /**
     * The fast path names the position and lets the host size it. That is
     * incompatible with an edited size — there is nowhere to put the number —
     * so an override drops through to the explicit path below, which sends an
     * amount and therefore honours it.
     *
     * **Except on a hedged position**, where the fast path is doing a second
     * job: `closePosition({ symbol, side })` names the LEG, and the shared
     * `PlaceOrderOptions` has no field that can. Silently dropping to a bare
     * reduce-only order there could reduce the wrong leg, so an edit is
     * refused rather than guessed at. Hedged positions on inverse or
     * contract-sized markets already take the sized path, so this narrows to
     * exactly the case the fast path was protecting.
     */
    if (edit?.price !== undefined) {
      // A close is a market order. Silently dropping a typed price would leave
      // the user believing they had set one.
      out.reasons.push(`a ${position.symbol} close on ${position.account} is a market order — it takes no price`);
      continue;
    }
    if (edit?.amount !== undefined && fastPathFits && position.positionMode === 'hedged') {
      out.reasons.push(
        `the size of a hedged ${position.symbol} close on ${position.account} cannot be edited — ` +
          'ask again with the size you want',
      );
      continue;
    }
    if (edit?.amount === undefined && fastPathFits) {
      out.commands.push({
        method: 'closePosition',
        args: [{ symbol: position.symbol, side: position.side }, position.account],
        preview: `Close ${trim(position.contracts)} ${position.symbol} ${position.side} on ${position.account}`,
        // A one-way linear close IS editable — the edit drops it to the sized
        // path below. A HEDGED one is refused there, because `closePosition`
        // names the leg and `PlaceOrderOptions` cannot, so it must not offer
        // a pencil whose only outcome is that rejection.
        ...(position.positionMode === 'hedged'
          ? {}
          : {
              editable: {
                symbol: position.symbol,
                account: position.account,
                side: closeSideOf(position),
                amount: Math.abs(position.nativeContracts),
              },
            }),
      });
      continue;
    }

    const sized = sizeClose(position, 1, market, edit?.amount);
    if ('reason' in sized) {
      out.reasons.push(sized.reason);
      continue;
    }
    out.commands.push(
      closeCommand(
        position,
        sized.amount,
        `Close ${trim(sized.amount)} ${position.symbol} ${position.side} on ${position.account}`,
      ),
    );
  }
  return out;
};

const resolveCancel = (
  context: OemsContext,
  lookups: Lookups,
  step: Extract<OemsIntent, { kind: 'cancel_orders' }>,
): StepOutput => {
  const out = empty();
  const orders = matchOrders(context, step.scope);
  if (orders.length === 0) {
    out.reasons.push('no open orders match that description');
    return out;
  }

  const byAccount = new Map<string, OemsOrderRef[]>();
  for (const order of orders) {
    const list = byAccount.get(order.account);
    if (list) list.push(order);
    else byAccount.set(order.account, [order]);
  }

  for (const [account, list] of byAccount) {
    const problem = lookups.accountProblem(account);
    if (problem) {
      out.reasons.push(problem);
      continue;
    }
    if (list.length === 1) {
      out.commands.push({
        method: 'cancelOrder',
        args: [list[0].id, { account, symbol: list[0].symbol }],
        preview: `Cancel ${list[0].side} ${trim(list[0].remaining)} ${list[0].symbol} on ${account}`,
      });
      continue;
    }
    // Chunked rather than refused: the host caps one call at MAX_CANCEL_BATCH
    // because several venues cancel one round-trip per order.
    for (let index = 0; index < list.length; index += MAX_CANCEL_BATCH) {
      const chunk = list.slice(index, index + MAX_CANCEL_BATCH);
      out.commands.push({
        method: 'cancelOrders',
        // An id list, not a symbol/side filter: the preview says "Cancel 25
        // orders" and a filter would cancel every order matching it.
        args: [{ ids: chunk.map((order) => order.id) }, account],
        preview: `Cancel ${chunk.length} orders on ${account}`,
      });
    }
  }
  return out;
};

/** Mirrors `convertFromNativeSizeToQuote`: an inverse contract is already
 *  sized in quote, a linear one is base and needs the price. */
const quoteNotional = (amount: number, price: number, market: OemsMarketRef): number => {
  const size = amount * (market.contractSize || 1);
  return market.isInverse ? size : size * price;
};

const resolvePlace = (
  context: OemsContext,
  lookups: Lookups,
  rawStep: Extract<OemsIntent, { kind: 'place_order' }>,
  stepIndex: number,
  overrides?: readonly OemsOverride[],
): StepOutput => {
  // An override rewrites the STEP, before a single check has run. Everything
  // below — lot-step rounding, min/max amount, the fat-finger notional — then
  // applies to the user's number exactly as it would to the model's.
  const edit = overrideFor(overrides, {
    step: stepIndex,
    symbol: rawStep.symbol,
    account: rawStep.account,
    side: rawStep.side,
  });
  const step =
    edit === undefined
      ? rawStep
      : {
          ...rawStep,
          ...(edit.amount !== undefined ? { amount: edit.amount } : {}),
          ...(edit.price !== undefined && rawStep.orderType !== 'market' ? { price: edit.price } : {}),
        };
  const out = empty();
  const problem = lookups.accountProblem(step.account);
  if (problem) {
    out.reasons.push(problem);
    return out;
  }
  const market = lookups.marketFor(step.account, step.symbol);
  if (!market) {
    out.reasons.push(noMarket(step.symbol, step.account));
    return out;
  }
  if (step.orderType === 'limit' && !(step.price !== undefined && step.price > 0)) {
    out.reasons.push('a limit order needs a positive price');
    return out;
  }
  if (step.orderType === 'market' && step.price !== undefined) {
    out.reasons.push('a market order cannot carry a price');
    return out;
  }
  if (step.reduceOnly && market.isSpot) {
    out.reasons.push(`${step.symbol} on ${step.account} is a spot market — there is no position to reduce`);
    return out;
  }
  if (
    step.reduceOnly &&
    !context.positions.some(
      (position) => position.account === step.account && upper(position.symbol) === upper(step.symbol),
    )
  ) {
    out.reasons.push(`no open ${step.symbol} position on ${step.account} to reduce`);
    return out;
  }

  const amount = roundToStep(step.amount, market.amountStep);
  if (!(amount > 0)) {
    out.reasons.push(`${trim(step.amount)} ${step.symbol} rounds to zero at this market's lot step`);
    return out;
  }
  if (limitsComparable(market)) {
    if (market.minAmount > 0 && amount < market.minAmount) {
      out.reasons.push(`${trim(amount)} ${step.symbol} is below the ${trim(market.minAmount)} minimum`);
      return out;
    }
    if (market.maxAmount > 0 && amount > market.maxAmount) {
      out.reasons.push(`${trim(amount)} ${step.symbol} is above the ${trim(market.maxAmount)} maximum`);
      return out;
    }
  }

  const price = step.price === undefined ? undefined : roundToStep(step.price, market.priceStep);

  // The host exempts reduce-only and stop/TP orders from fat-finger, so this
  // must too — refusing a close because the position is large would be the
  // protection working backwards.
  if (context.fatFingerNotional > 0 && !step.reduceOnly) {
    const reference = price ?? market.lastPrice;
    // A linear notional needs a price. Without one this used to read as 0 and
    // pass, so a market order on a symbol with no ticker skipped the limit.
    if (!market.isInverse && !(reference > 0)) {
      out.reasons.push(
        `there is no price for ${step.symbol} to check your fat-finger limit against; give a limit price`,
      );
      return out;
    }
    const notional = quoteNotional(amount, reference, market);
    if (notional > context.fatFingerNotional) {
      out.reasons.push(
        `that is about ${trim(notional)} notional, over your ${trim(context.fatFingerNotional)} fat-finger limit`,
      );
      return out;
    }
  }

  const options: Record<string, unknown> = { amount };
  if (price !== undefined) options.price = price;
  if (step.reduceOnly) options.reduceOnly = true;

  out.commands.push({
    method: 'placeOrder',
    args: [{ ...options, symbol: step.symbol, side: step.side, type: step.orderType }, step.account],
    preview:
      `${step.side === 'buy' ? 'Buy' : 'Sell'} ${trim(amount)} ${step.symbol} on ${step.account} ` +
      `${price === undefined ? 'at market' : `at ${trim(price)}`}${step.reduceOnly ? ' (reduce only)' : ''}`,
    // From the post-override `step`, so re-reading a card after an edit shows
    // the edited number and editing again is idempotent. `price` is omitted on
    // a market order, which takes none.
    editable: {
      symbol: step.symbol,
      account: step.account,
      side: step.side,
      amount,
      ...(price !== undefined ? { price } : {}),
    },
  });
  return out;
};

const resolveStop = (
  context: OemsContext,
  lookups: Lookups,
  rawStep: Extract<OemsIntent, { kind: 'place_stop_loss' }>,
  stepIndex: number,
  overrides?: readonly OemsOverride[],
): StepOutput => {
  // Same rewrite-the-step shape as `resolvePlace`. A stop's trigger is carried
  // in `price`, so that is the field an edited trigger replaces.
  const edit = overrideFor(overrides, {
    step: stepIndex,
    symbol: rawStep.symbol,
    account: rawStep.account,
    side: rawStep.side,
  });
  const step =
    edit === undefined
      ? rawStep
      : {
          ...rawStep,
          ...(edit.amount !== undefined ? { amount: edit.amount } : {}),
          ...(edit.price !== undefined ? { price: edit.price } : {}),
        };
  const out = empty();
  const problem = lookups.accountProblem(step.account);
  if (problem) {
    out.reasons.push(problem);
    return out;
  }
  const market = lookups.marketFor(step.account, step.symbol);
  if (!market) {
    out.reasons.push(noMarket(step.symbol, step.account));
    return out;
  }
  if (!(step.price > 0)) {
    out.reasons.push('a stop needs a positive trigger price');
    return out;
  }

  /**
   * `createStopLossOrder` hardcodes `reduceOnly` and derives the order TYPE by
   * comparing the trigger to the mark. Two consequences worth refusing here
   * rather than discovering after the fact: a stop with no position to protect
   * is a call that cannot do anything, and a trigger on the wrong side of the
   * market silently comes out a TAKE-PROFIT — the opposite instruction.
   */
  const protects = context.positions.find(
    (position) =>
      position.account === step.account &&
      upper(position.symbol) === upper(step.symbol) &&
      (position.side === 'long') === (step.side === 'sell'),
  );
  if (!protects) {
    out.reasons.push(
      `no ${step.side === 'sell' ? 'long' : 'short'} position on ${step.symbol} at ${step.account} to protect`,
    );
    return out;
  }

  /**
   * A trigger on the wrong side of the market fills the moment it is placed.
   *
   * The boundary mirrors `createStopLossOrder`'s own `slIsValid` — `sell` needs
   * a price BELOW the reference, `buy` needs at-or-above — so a buy stop
   * exactly at the reference is not refused here either.
   *
   * The reference is approximate: the host compares against whichever trigger
   * type the user selected (mark or index, defaulting to last), and only last
   * is in this snapshot. That is tolerable now that the command names
   * `type: 'stop_market'` explicitly, so a wrong-side trigger can no longer
   * flip the order into a take-profit — the remaining risk is an immediate
   * fill, and refusing it is the better error.
   */
  const reference = market.lastPrice > 0 ? market.lastPrice : protects.markPrice;
  if (reference > 0) {
    const wrongSide = step.side === 'sell' ? step.price >= reference : step.price < reference;
    if (wrongSide) {
      out.reasons.push(
        `a ${step.side} stop must trigger ${step.side === 'sell' ? 'below' : 'above'} the current ` +
          `${trim(reference)} — at ${trim(step.price)} it would fill immediately`,
      );
      return out;
    }
  }

  const amount = roundToStep(step.amount, market.amountStep);
  if (!(amount > 0)) {
    out.reasons.push(`${trim(step.amount)} ${step.symbol} rounds to zero at this market's lot step`);
    return out;
  }

  const price = roundToStep(step.price, market.priceStep);
  out.commands.push({
    method: 'placeOrder',
    // The type is stated rather than left to be derived from the trigger
    // against a mark that may have moved since this snapshot — that derivation
    // is how a stop silently becomes a take-profit.
    // `reduceOnly` is hardcoded, exactly as `createStopLossOrder` does: a
    // protective stop that is allowed to OPEN a position is not a protective
    // stop, and nothing in the intent says otherwise.
    args: [
      { symbol: step.symbol, side: step.side, type: 'stop_market', amount, price, reduceOnly: true },
      step.account,
    ],
    preview: `Stop ${step.side} ${trim(amount)} ${step.symbol} on ${step.account} triggered at ${trim(price)}`,
    // A stop's editable price IS its trigger — the field it is carried in.
    editable: { symbol: step.symbol, account: step.account, side: step.side, amount, price },
  });
  return out;
};

const resolveAmend = (
  context: OemsContext,
  lookups: Lookups,
  step: Extract<OemsIntent, { kind: 'amend_order' }>,
): StepOutput => {
  const out = empty();
  const problem = lookups.accountProblem(step.account);
  if (problem) {
    out.reasons.push(problem);
    return out;
  }
  const order = context.orders.find((candidate) => candidate.account === step.account && candidate.id === step.orderId);
  if (!order) {
    out.reasons.push(`no open order ${step.orderId} on ${step.account}`);
    return out;
  }

  const hasPrice = step.price !== undefined;
  const hasAmount = step.amount !== undefined;
  if (hasPrice === hasAmount) {
    out.reasons.push('an amend must change exactly one of price or amount');
    return out;
  }

  const market = lookups.marketFor(step.account, order.symbol);
  if (!market) {
    out.reasons.push(noMarket(order.symbol, step.account));
    return out;
  }

  // Round to NEAREST for an amend even where placement rounds down: truncating
  // a resting order's size is a change the user did not ask for.
  const update = hasPrice
    ? { price: roundToStep(step.price as number, market.priceStep) }
    : { amount: roundToStep(step.amount as number, market.amountStep) };
  const value = hasPrice ? (update as { price: number }).price : (update as { amount: number }).amount;
  if (!(value > 0)) {
    out.reasons.push(`the amended ${hasPrice ? 'price' : 'amount'} rounds to zero`);
    return out;
  }

  out.commands.push({
    method: 'updateOrder',
    args: [order.id, { update }, step.account],
    preview: `Amend ${order.symbol} ${order.side} on ${step.account} — ${hasPrice ? 'price' : 'amount'} to ${trim(value)}`,
  });
  return out;
};

const resolveLeverage = (
  context: OemsContext,
  lookups: Lookups,
  step: Extract<OemsIntent, { kind: 'set_leverage' }>,
): StepOutput => {
  const out = empty();
  const problem = lookups.accountProblem(step.account);
  if (problem) {
    out.reasons.push(problem);
    return out;
  }
  const market = lookups.marketFor(step.account, step.symbol);
  if (!market) {
    out.reasons.push(noMarket(step.symbol, step.account));
    return out;
  }
  if (market.isSpot) {
    out.reasons.push(`${step.symbol} on ${step.account} is a spot market and has no leverage`);
    return out;
  }
  if (!Number.isFinite(step.leverage) || step.leverage <= 0 || step.leverage > MAX_LEVERAGE) {
    out.reasons.push(`leverage must be between 0 and ${MAX_LEVERAGE}`);
    return out;
  }
  if (market.maxLeverage > 0 && step.leverage > market.maxLeverage) {
    out.reasons.push(`${step.symbol} on ${step.account} allows at most ${trim(market.maxLeverage)}x`);
    return out;
  }

  /** In hedged mode the two legs carry their own leverage, so an unsided call
   *  is ambiguous rather than merely imprecise. */
  const hedged = context.positions.some(
    (position) =>
      position.account === step.account &&
      upper(position.symbol) === upper(step.symbol) &&
      position.positionMode === 'hedged',
  );
  if (hedged && step.side === undefined) {
    out.reasons.push(`${step.account} holds ${step.symbol} in hedge mode — say which leg, long or short`);
    return out;
  }

  out.commands.push({
    method: 'setLeverage',
    // The side is OMITTED rather than passed as `undefined`: anything that
    // serialises these args on the way to the adapter turns one into the other,
    // and `null` is not an absent leg.
    args:
      step.side === undefined
        ? [step.symbol, step.leverage, step.account]
        : [step.symbol, step.leverage, step.account, step.side],
    preview: `Set ${step.symbol} leverage to ${trim(step.leverage)}x on ${step.account}`,
  });
  return out;
};

/**
 * `cancel_orders`, `amend_order` and `set_leverage` take no overrides, and
 * that is deliberate rather than unfinished: a cancel has no size, and an
 * amend's number IS the user's already — it comes off the step, not off a
 * position, so editing it means editing the request rather than overriding a
 * derived value. The UI offers no edit affordance on those rows.
 */
const resolveStep = (
  context: OemsContext,
  lookups: Lookups,
  step: OemsIntent,
  index: number,
  overrides?: readonly OemsOverride[],
): StepOutput => {
  switch (step.kind) {
    case 'reduce_positions':
      return resolveReduce(context, lookups, step, index, overrides);
    case 'close_positions':
      return resolveClose(context, lookups, step, index, overrides);
    case 'cancel_orders':
      return resolveCancel(context, lookups, step);
    case 'place_order':
      return resolvePlace(context, lookups, step, index, overrides);
    case 'place_stop_loss':
      return resolveStop(context, lookups, step, index, overrides);
    case 'amend_order':
      return resolveAmend(context, lookups, step);
    case 'set_leverage':
      return resolveLeverage(context, lookups, step);
  }
};

export const resolveOemsPlan = (plan: OemsPlan, context: OemsContext, options: ResolveOptions = {}): OemsResolution => {
  const maxAge = options.maxContextAgeMs ?? DEFAULT_MAX_CONTEXT_AGE_MS;
  const age = (options.now ?? Date.now()) - context.generatedAt;
  if (age > maxAge) {
    const stale = `the snapshot of your book is ${Math.round(age / 1000)}s old — ask again`;
    return {
      commands: [],
      rejections: plan.steps.map((step, index) => ({ step: index, kind: step.kind, reason: stale })),
    };
  }

  const lookups = buildLookups(context);
  const commands: OemsCommand[] = [];
  const rejections: OemsRejection[] = [];

  plan.steps.forEach((step, index) => {
    const { commands: produced, reasons } = resolveStep(context, lookups, step, index, options.overrides);
    // Stamped centrally so no individual command builder has to know its own
    // index — they are written per intent kind and several are shared.
    for (const command of produced) commands.push({ ...command, step: index });
    for (const reason of reasons) rejections.push({ step: index, kind: step.kind, reason });
  });

  return { commands, rejections };
};
