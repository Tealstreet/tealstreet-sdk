import { beforeEach, describe, expect, it } from 'vitest';

import { createRemoteSigningAdapter } from '../remoteSigningAdapter';

import {
  drainVenueRestFailureSamples,
  getVenueRestStats,
  markRestRequestStart,
  markRestSigned,
  markRestProxyHeader,
  noteRestFailure,
  noteRestSuccess,
  resetVenueRestDiagnostics,
} from './venueRestDiagnostics';

const statsFor = (exchange: string) => getVenueRestStats()[exchange] as Record<string, any>;

describe('venueRestDiagnostics', () => {
  beforeEach(() => {
    resetVenueRestDiagnostics();
  });

  // The headers bybit returns on every private response. Nothing read these
  // before, so how close the poll runs to the venue's limit was unobservable
  // without waiting for a failure.
  it('tracks the lowest remaining venue quota seen', () => {
    noteRestSuccess('bybit', { config: {}, headers: { 'X-Bapi-Limit': '10', 'X-Bapi-Limit-Status': '7' } });
    noteRestSuccess('bybit', { config: {}, headers: { 'X-Bapi-Limit': '10', 'X-Bapi-Limit-Status': '2' } });
    noteRestSuccess('bybit', { config: {}, headers: { 'X-Bapi-Limit': '10', 'X-Bapi-Limit-Status': '6' } });

    expect(statsFor('bybit').minQuotaRemaining).toBe(2);
    expect(statsFor('bybit').lastQuota).toMatchObject({ 'x-bapi-limit-status': '6' });
  });

  // A CloudFront 401 reads the same whether we sent no credential or sent one
  // the edge rejected, and the body that would have named the difference
  // arrives in Sentry as `[Filtered]`. This field is the only thing that can
  // settle it.
  it('records that the request carried proxy auth', () => {
    const config: Record<string, unknown> = markRestProxyHeader({ url: '/api/v5/account/config' });
    config.headers = { Authorization: 'Bearer a-real-looking-token' };
    noteRestFailure('okx', { config, response: { status: 401, headers: {}, data: 'x' } } as never);

    expect(drainVenueRestFailureSamples()[0].restProxyHeaderSent).toBe('bearer');
  });

  // The exact contradiction that cost half a day: the interceptor stamped its
  // intent, the merge downstream dropped the header, and the sample reported
  // the intent. It must report the wire.
  it('reports absent when the stamp says we intended to send one but nothing survived', () => {
    const config = markRestProxyHeader({ url: '/api/v5/account/config' });
    noteRestFailure('okx', { config, response: { status: 401, headers: {}, data: 'x' } } as never);

    expect(drainVenueRestFailureSamples()[0].restProxyHeaderSent).toBe('absent');
  });

  it('flags a credential that is present but not a bearer', () => {
    const config: Record<string, unknown> = markRestProxyHeader({ url: '/api/v5/account/config' });
    config.headers = { Authorization: 'notabearer' };
    noteRestFailure('okx', { config, response: { status: 401, headers: {}, data: 'x' } } as never);

    expect(drainVenueRestFailureSamples()[0].restProxyHeaderSent).toBe('malformed');
  });

  // Undefined rather than a third value: the REST proxy was not in play. Note
  // that is NOT the same as unauthenticated — a tunnelled venue resolves no
  // proxy URL and still carries our credential on the HOW socket.
  it('leaves proxy auth unset for a request that never went through the proxy', () => {
    noteRestFailure('okx', {
      config: { url: '/api/v5/account/config' },
      response: { status: 500, headers: {}, data: 'boom' },
    } as never);

    expect(drainVenueRestFailureSamples()[0].restProxyHeaderSent).toBeUndefined();
  });

  it('reads quota headers off an AxiosHeaders-style response', () => {
    const headers = { get: (name: string) => (name === 'x-bapi-limit-status' ? '3' : undefined) };

    noteRestSuccess('bybit', { config: {}, headers });

    expect(statsFor('bybit').minQuotaRemaining).toBe(3);
  });

  // A bare 403 with an HTML body is something in FRONT of the venue answering.
  // Which one it is only shows in the body and the origin headers.
  it('classifies a non-venue error body and keeps the headers that name the layer', () => {
    noteRestFailure('bybit', {
      config: { url: '/v5/position/list?api_key=abc&sign=def' },
      code: 'ERR_BAD_REQUEST',
      response: {
        status: 403,
        headers: { Server: 'CloudFront', 'X-Cache': 'Error from cloudfront', 'Retry-After': '30' },
        data: '<html><body>Generated by cloudfront (CloudFront)</body></html>',
      },
    });

    const [sample] = drainVenueRestFailureSamples();
    expect(sample.bodyKind).toBe('cloudfront');
    expect(sample.headers).toMatchObject({ server: 'CloudFront', 'retry-after': '30' });
    expect(sample.status).toBe(403);
  });

  // The query string carries the signature and the api key on several venues.
  it('stores the path without the query string', () => {
    noteRestFailure('bybit', {
      config: { url: '/v5/position/list?api_key=SECRETKEY&sign=SIGNATURE' },
      response: { status: 403, headers: {}, data: '' },
    });

    const [sample] = drainVenueRestFailureSamples();
    expect(sample.path).toBe('/v5/position/list');
    expect(JSON.stringify(sample)).not.toContain('SECRETKEY');
  });

  // Bybit API keys are 18 characters, so a 20-char floor would have let one
  // through had a venue ever echoed it back in an HTML error page.
  it('redacts a token shorter than twenty characters', () => {
    noteRestFailure('bybit', {
      config: {},
      response: { status: 403, headers: {}, data: 'rejected for key ABCDEFGH1234567890' },
    });

    const [sample] = drainVenueRestFailureSamples();
    expect(sample.bodySnippet).not.toContain('ABCDEFGH1234567890');
  });

  // The three remote-signer failures differ only in wording, and a 12-char
  // length rule ate the words that tell them apart.
  it('keeps ordinary long words that are not secrets', () => {
    noteRestFailure('bybit', new Error('WebSocket disconnected — signing aborted'));
    noteRestFailure('bybit', new Error('Remote signer unavailable — WebSocket disconnected'));

    const samples = drainVenueRestFailureSamples();
    expect(samples[0].errorMessage).toBe('WebSocket disconnected — signing aborted');
    expect(Object.keys(statsFor('bybit').errorCounts).sort()).toEqual([
      'Remote signer unavailable — WebSocket disconnected',
      'WebSocket disconnected — signing aborted',
    ]);
  });

  // The real messages carry an exchange prefix, so the part that distinguishes
  // them starts past character 60 — where the key used to be cut.
  it('keeps the discriminator when it falls late in a prefixed message', () => {
    noteRestFailure(
      'bybit',
      new Error('[bybit] Request setup error: Remote signer unavailable — WebSocket disconnected (gone <5s)'),
    );
    noteRestFailure(
      'bybit',
      new Error('[bybit] Request setup error: Remote signer unavailable — WebSocket disconnected (gone >10m)'),
    );

    expect(Object.keys(statsFor('bybit').errorCounts)).toHaveLength(2);
  });

  it('still redacts a mixed letter-and-digit token', () => {
    noteRestFailure('bybit', new Error('Signing request V1StGXR8Z5jdHi6BmyT timed out'));

    const [sample] = drainVenueRestFailureSamples();
    expect(sample.errorMessage).toContain('<redacted>');
    expect(sample.errorMessage).not.toContain('V1StGXR8Z5jdHi6BmyT');
  });

  it('redacts key-shaped runs out of a body snippet', () => {
    noteRestFailure('bybit', {
      config: {},
      response: { status: 403, headers: {}, data: 'blocked request id AKIAIOSFODNN7EXAMPLEKEYLONG12345' },
    });

    const [sample] = drainVenueRestFailureSamples();
    expect(sample.bodySnippet).toContain('<redacted>');
    expect(sample.bodySnippet).not.toContain('AKIAIOSFODNN7EXAMPLEKEYLONG12345');
  });

  // A venue JSON error already reaches Sentry as the error message, so keeping
  // its text again would duplicate it into a second place.
  it('keeps no snippet for a venue JSON body', () => {
    noteRestFailure('bybit', {
      config: {},
      response: { status: 200, headers: {}, data: { retCode: 10006, retMsg: 'Too many visits' } },
    });

    const [sample] = drainVenueRestFailureSamples();
    expect(sample.bodyKind).toBe('venue-json');
    expect(sample.bodySnippet).toBeUndefined();
  });

  // Separates "the browser was slow to sign" from "the venue was slow", which
  // are one indistinguishable 20s timeout today.
  it('splits signing time out of total time', () => {
    const config = markRestSigned(markRestRequestStart({}, 1_000), 400, 1_400);

    noteRestSuccess('bybit', { config, headers: {} }, 1_900);

    expect(statsFor('bybit').totalP50Ms).toBe(900);
    expect(statsFor('bybit').signP50Ms).toBe(400);
  });

  // A signature that ages past the venue's recvWindow while queued is rejected
  // by the venue and looks nothing like a network fault.
  it('derives signature age from the stamped venue timestamp', () => {
    const config = markRestSigned({ headers: { 'X-BAPI-TIMESTAMP': '1000' } }, 50, 3_500);

    noteRestFailure('bybit', { config, response: { status: 403, headers: {}, data: '' } }, 3_600);

    expect(statsFor('bybit').maxSignatureAgeMs).toBe(2_500);
  });

  // The signing adapter hands over an `AxiosHeaders`, not a plain object. A
  // property read that missed would leave signature age permanently absent.
  it('reads the venue timestamp through an AxiosHeaders-style accessor', () => {
    const headers = { get: (name: string) => (name === 'x-bapi-timestamp' ? '1000' : undefined) };
    const config = markRestSigned({ headers }, 50, 2_000);

    noteRestFailure('bybit', { config, response: { status: 403, headers: {}, data: '' } }, 2_100);

    expect(statsFor('bybit').maxSignatureAgeMs).toBe(1_000);
  });

  it('counts statuses and codes so a burst has a shape', () => {
    noteRestFailure('bybit', { config: {}, code: 'ECONNABORTED' });
    noteRestFailure('bybit', { config: {}, code: 'ECONNRESET' });
    noteRestFailure('bybit', { config: {}, response: { status: 403, headers: {}, data: '' } });
    noteRestSuccess('bybit', { config: {}, headers: {} });

    expect(statsFor('bybit')).toMatchObject({
      requests: 4,
      ok: 1,
      failures: 3,
      statusCounts: { none: 2, '403': 1 },
      codeCounts: { ECONNABORTED: 1, ECONNRESET: 1 },
    });
  });

  // /healthz is pull-only and nothing polls it, so pruning in the reader alone
  // would let this grow for the life of the container.
  it('drops out-of-window timestamps as they are written, not when read', () => {
    for (let i = 0; i < 50; i++) noteRestSuccess('bybit', { config: {}, headers: {} }, 1_000_000 + i);
    noteRestSuccess('bybit', { config: {}, headers: {} }, 1_000_000 + 50 + 6 * 60_000);

    expect(statsFor('bybit').trackedSamples).toBe(1);
    expect(statsFor('bybit').requests).toBe(51);
  });

  // The shape 408 bybit failures arrived in: no response, no code, no config,
  // no url. Every field this module was built around is empty, so the message
  // is the only thing that identifies the cause.
  it('names a bare thrown error that carries no response or code', () => {
    const error = Object.assign(new Error('Remote signing failed: signer timed out after 15000ms'), {
      name: 'Error',
    });

    noteRestFailure('bybit', error);

    const [sample] = drainVenueRestFailureSamples();
    expect(sample.errorMessage).toContain('Remote signing failed');
    expect(statsFor('bybit').errorCounts).toEqual({
      'Remote signing failed: signer timed out after #ms': 1,
    });
  });

  // One cause must be one key, or a per-request id turns the map into a log.
  it('collapses digits so one cause is one key', () => {
    noteRestFailure('bybit', new Error('Remote signing failed: request 8471 timed out after 15000ms'));
    noteRestFailure('bybit', new Error('Remote signing failed: request 9302 timed out after 15000ms'));

    expect(Object.values(statsFor('bybit').errorCounts)).toEqual([2]);
  });

  it('bounds the error key map', () => {
    for (let i = 0; i < 40; i++) noteRestFailure('bybit', new Error(`distinct failure kind ${String.fromCharCode(65 + i)}`));

    expect(Object.keys(statsFor('bybit').errorCounts).length).toBeLessThanOrEqual(21);
    expect(statsFor('bybit').errorCounts.other).toBeGreaterThan(0);
  });

  // A venue error that DID answer already has a status and a body; counting its
  // text too would put venue prose into a public payload for no added signal.
  it('does not key an error that carries a response', () => {
    noteRestFailure('bybit', {
      config: {},
      message: 'Request failed with status code 403',
      response: { status: 403, headers: {}, data: '' },
    });

    expect(statsFor('bybit').errorCounts).toEqual({});
  });

  // Both the venue and our own tunnel sit behind CloudFront and return a
  // byte-identical error page, so the dialled host is what tells them apart.
  it('records the dialled endpoint, keeping the upstream a proxy embeds', () => {
    noteRestSuccess('bybit', { config: { baseURL: 'https://api.bybit.com' }, headers: {} });
    expect(statsFor('bybit').lastEndpoint).toBe('https://api.bybit.com');

    noteRestFailure('bybit', {
      config: { baseURL: 'https://fsjnpy143pbz.jp.tealstreet.io/https://api.bybit.com', url: '/v5/position/list' },
      response: { status: 403, headers: {}, data: '' },
    });

    const [sample] = drainVenueRestFailureSamples();
    expect(sample.endpoint).toBe('https://fsjnpy143pbz.jp.tealstreet.io/https://api.bybit.com');
  });

  it('strips a query string off the dialled endpoint', () => {
    noteRestFailure('bybit', {
      config: { url: 'https://api.bybit.com/v5/position/list?api_key=SECRETKEY&sign=SIG' },
      response: { status: 403, headers: {}, data: '' },
    });

    const [sample] = drainVenueRestFailureSamples();
    expect(sample.endpoint).toBe('https://api.bybit.com/v5/position/list');
    expect(JSON.stringify(sample)).not.toContain('SECRETKEY');
  });

  it('drains so one burst is not reported on every tick', () => {
    noteRestFailure('bybit', { config: {}, response: { status: 403, headers: {}, data: '' } });

    expect(drainVenueRestFailureSamples()).toHaveLength(1);
    expect(drainVenueRestFailureSamples()).toHaveLength(0);
  });

  it('never throws on a malformed error', () => {
    expect(() => noteRestFailure('bybit', undefined)).not.toThrow();
    expect(() => noteRestSuccess('bybit', null)).not.toThrow();
    expect(statsFor('bybit').requests).toBe(2);
  });
});

// The whole point of the change. `remoteSigningAdapter` rebuilds the config as
// `{...config}` before it reaches the inner adapter, and the response
// interceptor reads `response.config` — if either stamp were dropped in that
// spread the latency split would be silently absent forever rather than wrong.
describe('venueRestDiagnostics through the remote signing adapter', () => {
  beforeEach(() => {
    resetVenueRestDiagnostics();
  });

  it('carries the start and signing stamps onto response.config', async () => {
    const signer = {
      sign: async (request: any) => ({
        config: { headers: { 'X-BAPI-TIMESTAMP': '1000' }, url: request.config.url, params: {}, data: undefined },
      }),
    };
    const innerAdapter = async (config: any) => ({ status: 200, data: {}, headers: {}, config });
    const adapter = createRemoteSigningAdapter(signer as any, 'bybit' as any, () => innerAdapter as any, 'acct');

    const config = markRestRequestStart({ method: 'GET', url: '/v5/position/list', headers: {} }, 1_000);
    const response = await adapter(config as any);

    noteRestSuccess('bybit', response, 2_000);

    expect(statsFor('bybit').totalP50Ms).toBe(1_000);
    expect(typeof statsFor('bybit').signP50Ms).toBe('number');
  });

  // A backgrounded phone's signer is gone for minutes at a time, and every poll in
  // that window used to file a "venue REST failure" the venue never saw.
  it.each([
    '[bybit] Request setup error: Remote signer unavailable — WebSocket disconnected (gone <5s)',
    'WebSocket disconnected — signing aborted',
    'Signing request abc timed out after 15000ms',
  ])('does not count an unsent signing failure as a venue failure: %s', (message) => {
    noteRestFailure('bybit', new Error(message));

    const stats = statsFor('bybit');
    expect(stats.failures).toBe(0);
    expect(stats.requests).toBe(0);
    expect(stats.perMinute).toBe(0);
    expect(stats.unsentSigning).toBe(1);
    expect(drainVenueRestFailureSamples()[0].unsentSigning).toBe(true);
  });

  it('still counts a failure the venue answered as a venue failure', () => {
    noteRestFailure('bybit', { config: {}, response: { status: 403, headers: {}, data: '<html>ERROR</html>' } });

    expect(statsFor('bybit').failures).toBe(1);
    expect(drainVenueRestFailureSamples()[0].unsentSigning).toBe(false);
  });

  // CloudFront's reason line sits after its <head> and styles, past the snippet cut.
  it('keeps the readable reason from a CloudFront error page', () => {
    const page = `<!DOCTYPE HTML><HTML><HEAD><META HTTP-EQUIV="Content-Type" CONTENT="text/html"><TITLE>ERROR: The request could not be satisfied</TITLE><style>${'body{margin:0}'.repeat(30)}</style></HEAD><BODY><H1>403 ERROR</H1><H2>The request could not be satisfied.</H2><HR noshade size="1px">Request blocked. We can't connect to the server for this app or website at this time.<BR clear="all">Generated by cloudfront (CloudFront)</BODY></HTML>`;
    noteRestFailure('bybit', { config: {}, response: { status: 403, headers: {}, data: page } });

    const [sample] = drainVenueRestFailureSamples();
    expect(sample.bodyKind).toBe('cloudfront');
    expect(sample.bodySnippet).toContain('Request blocked');
  });
});
