/**
 * Emits the machine-readable read-surface manifest specified in
 * `docs/custom-scripts/SPEC.md` §10.
 *
 * This generator threw for the whole of Phase 6. The consequence was not that
 * nothing consumed a manifest — it was that every shell needing one wrote its
 * own. See `docs/plans/SDK_SURFACE_VISION_v1.md`.
 *
 * ## Who consumes THIS and who consumes the bindings
 *
 * The manifest is `ReadBinding` with `invoke` removed, so it is for a caller
 * that only has to DESCRIBE the surface: `oems-core` builds the agent's tool
 * list, its structured-output schema and its prompt block from it, and never
 * calls anything. A shell that also EXECUTES — the CLI's stdio MCP server —
 * imports `CORE_READ_BINDINGS` directly, because it needs the `invoke` the
 * manifest deliberately drops. Both project the same definition; only one
 * projects this artifact.
 *
 * ## Render lives here, and so does the artifact
 *
 * `mirrors/copy.bara.sky` carries `packages/script-api-core/**` into the OSS
 * `tealstreet-sdk` mirror but NOT the repo-root `scripts/**`. Keeping
 * `renderManifestFile` in this package means the drift gate runs inside the
 * mirror as well; the root orchestrator only decides where to write.
 *
 * The artifact lands in `src/runtime/` rather than beside the types bundle in
 * `script-authoring`, because THIS package is its source of truth and because
 * `oems-core` — the agent's contract package — depends on `script-api-core`
 * and not on `script-authoring`. Reaching the manifest through that package
 * would mean either a new dependency or a barrel import that drags the
 * TypeScript compiler (`validateScript`) into the browser bundle.
 */
import type { ReadManifestEntry } from '../src/runtime/readBindings';

import { CORE_READ_BINDINGS, toManifestEntry } from '../src/runtime/readBindings';

/** Sorted by method name so the artifact is stable across object-key reorders. */
export function generateCoreReadManifest(): readonly ReadManifestEntry[] {
  return Object.values(CORE_READ_BINDINGS)
    .map(toManifestEntry)
    .sort((a, b) => a.method.localeCompare(b.method));
}

const BANNER = `/**
 * AUTO-GENERATED by \`yarn generate:types\`. DO NOT EDIT.
 *
 * Source generator:
 *   packages/script-api-core/scripts/generate-manifest.ts
 * Source of truth:
 *   packages/script-api-core/src/runtime/readBindings.ts
 *
 * The drift test \`packages/script-api-core/src/runtime/read-manifest.test.ts\`
 * fails in CI if this file is out of sync with the generator. Run
 * \`yarn generate:types\` and commit.
 *
 * The read surface is DESCRIBED once, in \`readBindings.ts\`. A shell that only
 * has to describe it to a model consumes this artifact (the web agent's tool
 * list, schema and prompt block, all via \`oems-core\`); a shell that also has
 * to CALL it imports the bindings, for the \`invoke\` this drops. Neither
 * restates the vocabulary. See docs/plans/SDK_SURFACE_VISION_v1.md.
 */
`;

export function renderManifestFile(entries: readonly ReadManifestEntry[]): string {
  return [
    BANNER,
    "import type { ReadManifestEntry } from './readBindings';",
    '',
    `export const CORE_READ_MANIFEST: readonly ReadManifestEntry[] = ${JSON.stringify(entries, null, 2)};`,
    '',
  ].join('\n');
}
