/** Shared by mirror regeneration, the drift gate, and the NX orchestrator. */
import { generateCoreMonacoTypes } from '../../script-api-core/scripts/generate-monaco-types';
import { generateWebMonacoTypes } from '../../script-api-web/scripts/generate-monaco-types';

function ambientModule(name: string, declarations: string): string {
  // Keep NX's terminal empty-export normalization: an empty export inside the
  // generated ambient module is redundant. Do not strip interior declarations.
  const body = declarations.replace(/\nexport\s*\{\s*\};\s*$/m, '').trimEnd();
  return `declare module '${name}' {\n${body}\n}\n`;
}

/** Render the complete committed file, including its banner and layout. */
export function renderBundleFile(core: string, web: string): string {
  // Preserve NX's banner byte-for-byte until its orchestrator imports this helper.
  const banner = `/**
 * AUTO-GENERATED by \`yarn generate:types\`. DO NOT EDIT.
 *
 * Source generators:
 *   packages/script-api-core/scripts/generate-monaco-types.ts
 *   packages/script-api-web/scripts/generate-monaco-types.ts
 *
 * The drift test \`packages/script-authoring/src/script-types-bundle.test.ts\` fails in
 * CI if this file is out of sync with the generators. Run
 * \`yarn generate:types\` and commit.
 */

`;
  return (
    banner +
    `export const CORE_TYPES_DTS = ${JSON.stringify(ambientModule('@tealstreet/script-api-core', core))};\n\n` +
    `export const WEB_TYPES_DTS = ${JSON.stringify(ambientModule('@tealstreet/script-api-web', web))};\n`
  );
}

/** Generate in memory; callers choose whether to compare or write the result. */
export function generateScriptTypesBundle(): string {
  return renderBundleFile(generateCoreMonacoTypes(), generateWebMonacoTypes());
}
