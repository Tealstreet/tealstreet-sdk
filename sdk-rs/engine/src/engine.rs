pub struct RequestId(pub u32);
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct TimerId(pub u32);
/// Correlates a [`Command`] with its [`Notice::CommandDone`].
pub type CommandId = u32;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Method {
    Get,
    Post,
    Put,
    Patch,
    Delete,
}

impl Method {
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Get => "GET",
            Self::Post => "POST",
            Self::Put => "PUT",
            Self::Patch => "PATCH",
            Self::Delete => "DELETE",
        }
    }
}

/// A public request can select a host-owned egress without naming a proxy URL.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum RequestRoute {
    /// A primary-account read must not use the secondary read identity/egress.
    Primary,
    Direct,
    PublicCors,
}
impl RequestRoute {
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Primary => "primary",
            Self::Direct => "direct",
            Self::PublicCors => "publicCors",
        }
    }
}

#[derive(Clone, Debug, PartialEq)]
pub struct HttpRequest {
    pub id: RequestId,
    pub method: Method,
    pub route: Option<RequestRoute>,
    pub timeout_ms: Option<u32>,
    pub url: String,
    pub headers: Vec<(&'static str, String)>,
    /// Delegated signer headers; fixed venue authentication headers take precedence.
    pub signer_headers: Vec<(String, String)>,
    pub body: Option<String>,
}

#[derive(Clone, Debug, PartialEq, serde::Serialize)]
#[serde(rename_all = "camelCase")]
pub struct PayloadSignRequest {
    pub exchange_name: &'static str,
    pub key: String,
    pub payload: String,
    pub scheme: &'static str,
    pub encoding: &'static str,
}

#[derive(Clone, Debug, PartialEq)]
pub enum SignatureTarget {
    Header(&'static str),
    /// The exact serialized signature field, generated by the venue.
    JsonField(String),
}

struct PendingSignature {
    http: HttpRequest,
    target: SignatureTarget,
    deadline: f64,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum LogLevel {
    Info,
    Warning,
    Error,
}

#[derive(Clone, Debug, PartialEq)]
pub enum Notice {
    /// Definitive credential rejection; transient failures never deactivate.
    Deactivate,
    Log {
        level: LogLevel,
        message: String,
    },
    /// `Ok` carries the command's JSON result.
    CommandDone {
        command: CommandId,
        result: Result<String, String>,
    },
    /// Startup cannot complete without intervention (bad configuration or an
    /// account the venue refuses); hosts fail `start` with it.
    StartupFailed {
        error: VenueError,
    },
    /// Completes a command with a structured failure; hosts report it like a
    /// `CommandDone` error, plus the detail.
    CommandFailed {
        command: CommandId,
        error: VenueError,
    },
}

