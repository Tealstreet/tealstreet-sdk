const VOLATILE = new Set(['timestamp', 'recvWindow', 'signature', 'newClientOrderId', 'clientAlgoId', 'requestId']);
// Connection IDs are generated by Bybit, while listen keys remain significant.
const canonicalMexcUrl = (url) => {
  const parsed = new URL(url);
  if (/\/private\/(planorder|stoporder)\/list\/orders$/.test(parsed.pathname)
    && parsed.searchParams.has('start_time') && parsed.searchParams.has('end_time')) {
    const end = Number(parsed.searchParams.get('end_time'));
    parsed.searchParams.set('start_time', String(Number(parsed.searchParams.get('start_time')) - end));
    parsed.searchParams.set('end_time', 'now');
  }
  const query = [...parsed.searchParams]
    .filter(([name, value]) => !VOLATILE.has(name) || callerIds.has(value))
    .map(([name, value]) => [name, /^[\[{]/.test(value) ? canonicalMexcBody(value) : value])
    .sort(([a], [b]) => a.localeCompare(b));
  return `${parsed.origin}${parsed.pathname}?${new URLSearchParams(query)}`;
};

// MEXC accepts snowflake order IDs as JSON numbers or strings. Keep that
// documented exception scoped to MEXC; other venues retain wire-type matching.
// Caller-supplied external IDs remain exact.
const canonicalMexcBody = (body) => {
  if (body === undefined || body === null || body === '') return '';
  let value = body;
  try {
    if (typeof body === 'string') value = parseRequestJson(body);
    else if (ArrayBuffer.isView(body) || body instanceof ArrayBuffer) value = parseRequestJson(new TextDecoder().decode(body));
  } catch { return String(body); }
  const sorted = (value) => {
    if (typeof value === 'bigint') return String(value);
    if (Array.isArray(value)) return value.map(sorted);
    if (value === null || typeof value !== 'object') return value;
    const keys = Object.keys(value).filter((key) => value[key] !== undefined
      && !(venue.volatileBodyFields && VOLATILE.has(key) && !callerIds.has(String(value[key])))
      && !(['externalOid', 'requestId'].includes(key) && !callerIds.has(String(value[key])))).sort();
    return Object.fromEntries(keys.map((key) => [
      key,
      !callerIds.has(value[key]) && venue.generatedBodyId?.(key, value[key]) ? '<generated>' : sorted(value[key]),
    ]));
  };
  return JSON.stringify(sorted(value), (_key, value) => typeof value === 'bigint' ? { integer: String(value) } : value);
};
const requestKey = (method, url, body) =>
  values.venue === 'mexc' ? `${method} ${canonicalMexcUrl(url)} ${canonicalMexcBody(body)}` : keyOf(method, url, body, callerIds, venue);

const isWriteRequest = (method, url) => venue.isWrite?.(method, url) ?? !isRead(method, url);

/** Serves recorded HTTP responses and websocket frames in tape order. */
class Tape extends SharedTape {
  constructor(impl) {
    super(records, { isPrivate });
    this.audit = venue.createSocketAudit?.(impl, { isPrivate, books: bookSymbols, tickers: venue.publicTickers?.(records) });
    this.responses = new Responses(records, requestKey, venue.checkRequest, isWriteRequest);
    this.commandIndex = 0;
    this.time = 0;
    this.subscriptions = new Set();
    // Retain expected keys/backing storage across both memory samples: deleting
    // startup-only harness state would subtract it from workload retained memory.
    this.startupSubscriptions = new Map(Array.from(venue.startupSubscriptions?.(records, bookSymbols) ?? [], (key) => [key, false]));
    this.pendingStartupSubscriptions = this.startupSubscriptions.size;
    this.generations = new Map();
  }

  respond(method, url, body, headers) {
    venue.validateRequest?.({ method, url, body, headers });
    const now = this.replayClock?.active ? this.replayClock.time - this.replayClock.epoch : this.time;
    const response = this.responses.respond(method, url, body, this.commandIndex, now);
    this.unserved = this.responses.unserved;
    if (response.status === 599) console.error(`Unserved or premature request: ${requestKey(method, url, body)}`);
    // Some tapes echo generated request IDs into native acknowledgements.
    if (/"\$(clientAlgoId|newClientOrderId)"/.test(response.body)) {
      let sent = body ?? {};
      if (ArrayBuffer.isView(sent) || sent instanceof ArrayBuffer) sent = new TextDecoder().decode(sent);
      if (typeof sent === 'string') sent = sent ? parseRequestJson(sent) : {};
      response.body = response.body.replace(/"\$(clientAlgoId|newClientOrderId)"/g,
        (_, field) => JSON.stringify(sent[field] ?? null));
    }
    return response;
  }
  connect(url, onOpen, onMessage, onClose) {
    let socket;
    socket = super.connect(url, onOpen, (text) => {
      this.audit?.received(url, text);
      if ((venue.validateLogin || venue.validateSubscriptions) && text.trimStart().startsWith('{')) {
        const message = JSON.parse(text);
        if (venue.validateLogin && message.event === 'login' && String(message.code) === '0' && !socket.loginVerified)
          throw new Error(`Taped login success preceded a valid login on ${url}`);
        this.assertSubscribed(socket, message);
      }
      onMessage(text);
    }, onClose);
    const key = socketUrl(url);
    socket.generation = (this.generations.get(key) ?? 0) + 1;
    this.generations.set(key, socket.generation);
    socket.loginVerified = false;
    socket.topics = new Map();
    return socket;
  }
  send(socket, text) {
    venue.onSocketSend?.(socket, text);
    for (const key of subscriptionKeys(socket.url, text)) {
      this.subscriptions.add(`${socket.generation} ${key}`);
      if (this.startupSubscriptions.get(key) === false) {
        this.startupSubscriptions.set(key, true);
        this.pendingStartupSubscriptions--;
      }
    }
    this.audit?.sent(socket.url, text);
    if (venue.pingReply) {
      const reply = venue.pingReply(text);
      if (reply) setImmediate(() => { if (!socket.closed) socket.onMessage(reply); });
    }
    if (venue.respondToPing && text === 'ping') {
      setImmediate(() => { if (!socket.closed) socket.onMessage('pong'); });
      return;
    }
    // OKX's opt-in auth validation also uses its v5 subscription argument model.
    const validateTopics = venue.validateSubscriptions ?? venue.validateLogin;
    if (!venue.validateLogin && !validateTopics) return;
    const message = JSON.parse(text);
    if (validateTopics && ['subscribe', 'unsubscribe'].includes(message.op)) {
      if (!Array.isArray(message.args)) throw new Error(`Invalid subscription on ${socket.url}`);
      for (const topic of message.args) {
        if (!topic || typeof topic.channel !== 'string' || !topic.channel) throw new Error(`Invalid subscription topic on ${socket.url}`);
        const key = JSON.stringify(Object.fromEntries(Object.entries(topic).sort(([a], [b]) => a.localeCompare(b))));
        if (message.op === 'subscribe') socket.topics.set(key, topic);
        else socket.topics.delete(key);
      }
      return;
    }
    if (!venue.validateLogin || !/\/(private|business)$/.test(new URL(socket.url).pathname)) return;
    if (message.op !== 'login') return;
    const arg = message.args?.length === 1 ? message.args[0] : undefined;
    const timestamp = String(arg?.timestamp ?? '');
    if (arg?.apiKey !== KEY || arg?.passphrase !== PASSPHRASE || !/^\d+$/.test(timestamp)
      || !Number.isSafeInteger(Number(timestamp)) || Math.abs(Number(timestamp) - Date.now() / 1000) > 30) {
      throw new Error(`Invalid OKX login credentials/timestamp on ${socket.url}`);
    }
    const expected = createHmac('sha256', SECRET).update(`${timestamp}GET/users/self/verify`).digest('base64');
    const supplied = Buffer.from(String(arg.sign ?? ''));
    const expectedBytes = Buffer.from(expected);
    if (supplied.length !== expectedBytes.length || !timingSafeEqual(supplied, expectedBytes)) {
      throw new Error(`Invalid OKX login signature on ${socket.url}`);
    }
    socket.loginVerified = true;
  }

  assertSubscribed(socket, message) {
    if (!(venue.validateSubscriptions ?? venue.validateLogin) || !message.arg?.channel || !Array.isArray(message.data)) return;
    const topics = [...socket.topics.values()].filter((topic) => topic.channel === message.arg.channel);
    // Some documented messages put instId only on each data row, not arg.
    const rows = message.data.length ? message.data : [null];
    for (const row of rows) {
      const object = row && !Array.isArray(row) && typeof row === 'object' ? row : {};
      const covered = topics.some((topic) => Object.entries(topic).every(([key, value]) => {
        if (key === 'channel') return true;
        if (key === 'instType' && value === 'ANY') return true;
        const values = [message.arg[key], object[key]].filter((v) => v !== undefined && v !== '');
        if (!values.length && key === 'instType') {
          const id = object.instId ?? message.arg.instId;
          if (id?.endsWith('-SWAP')) values.push('SWAP');
        }
        return values.length > 0 && values.every((v) => v === value);
      }));
      if (!covered) {
        throw new Error(`Unsubscribed ${message.arg.channel} frame on ${socket.url}: ${JSON.stringify(message.arg)}${object.instId ? ` instId=${object.instId}` : ''}`);
      }
    }
  }

  assertWritesConsumed() {
    const missing = this.responses.unusedWrites();
    if (missing) throw new Error(`${missing} taped write(s) were not sent`);
  }

  async socketFor(rawUrl, ordinal, text) {
    // Explicit ordinals identify same-URL sockets and reconnects. Older Phemex
    // tapes classify the authenticated socket from its outbound auth request.
    if (ordinal !== undefined || !venue.socketMatches || text === undefined) return super.socketFor(rawUrl, ordinal);
    const key = socketUrl(rawUrl);
    const find = () => [...this.open.values()].findLast((socket) =>
      !socket.closed && socket.key === key && venue.socketMatches(socket, text));
    const deadline = performance.now() + 15_000;
    while (!find()) {
      if (performance.now() > deadline) throw new Error(`Matching socket did not open: ${rawUrl}`);
      await new Promise((resolve) => realTimeout(resolve, 5));
    }
    return find();
  }

  async play(onTick, ready = async () => {}, runCommand = async () => {}, clock, begin = () => {}) {
    await within((async () => {
      for (const frame of this.frames.filter((frame) => venue.bootstrapFrame?.(frame))) {
        const socket = await this.socketFor(frame.url, frame.socket, frame.text);
        socket.onMessage(frame.text);
        await new Promise(setImmediate);
      }
      await ready();
      while (this.pendingStartupSubscriptions) await new Promise((resolve) => realTimeout(resolve, 1));
    })(), 15_000, 'Replay startup');
    begin();
    clock?.start();
    this.replayClock = clock;
    const start = performance.now();
    let delivered = 0;
    const warm = Math.floor(this.frames.reduce((count, frame) => count + (venue.bootstrapFrame?.(frame) ? 0 : 1), 0) / 4);
    for (const frame of this.frames) {
      if (venue.bootstrapFrame?.(frame)) continue;
      if (delivered === warm) this.warmMark = { thread: process.threadCpuUsage(), wall: performance.now() };
      if (isPrivate) {
        const wait = frame.t - (performance.now() - start);
        if (wait > 0) await new Promise((resolve) => setTimeout(resolve, wait));
      }
      this.time = frame.t;
      await clock?.advance(frame.t);
      if (frame.type === 'command') {
        this.commandIndex++;
        this.results.push(await within(runCommand(frame), 15_000, `Command ${frame.op}`).then(
          (ids) => ({ ok: ids }),
          (error) => {
            if (error instanceof ReplayTimeout) throw error;
            return { error: String(error?.message ?? error) };
          },
        ));
      } else {
        if (frame.type === 'close' && frame.socket === undefined && venue.socketMatches
          && [...this.open.values()].filter((socket) => !socket.closed && socket.key === socketUrl(frame.url)).length > 1) {
          throw new Error('Ambiguous close on a shared public/private endpoint');
        }
        const socket = await this.socketFor(frame.url, frame.socket, frame.text);
        if (frame.type === 'close') this.close(socket, frame.code);
        else if (frame.type === 'ws') socket.onMessage(frame.text);
      }
      delivered++;
      onTick?.(frame.t);
      await new Promise(setImmediate);
    }
    return delivered;
  }
  unusedWrites() { return this.responses.unusedWrites(); }
}

const settle = async () => {
  for (let i = 0; i < 20; i++) await new Promise(setImmediate);
};
const until = async (predicate, label) => {
  const deadline = performance.now() + 15000;
  while (!predicate()) {
    if (performance.now() > deadline) throw new Error(`Replay timed out waiting for ${label}`);
    await new Promise((resolve) => realTimeout(resolve, 5));
  }
};

const measure = async (cpuStart, wallStart, heapBefore, wasmBytes = 0, warmMark) => {
  const cpu = process.cpuUsage(cpuStart.process);
  const thread = process.threadCpuUsage(cpuStart.thread);
  const steady = warmMark ? process.threadCpuUsage(warmMark.thread) : { user: 0, system: 0 };
  const wallMs = performance.now() - wallStart;
  const memory = await baseline();
  return {
    // The worker's own thread: what competes with its message handling.
    cpuMs: (thread.user + thread.system) / 1000,
    // Main thread after the first quarter of frames: startup and JIT excluded.
    steadyCpuMs: (steady.user + steady.system) / 1000,
    // All threads, including V8 background compilation and GC helpers.
    processCpuMs: (cpu.user + cpu.system) / 1000,
    wallMs,
    rssBytes: memory.rss,
    heapUsedBytes: memory.heapUsed,
    heapRetainedBytes: memory.heapUsed - heapBefore.heapUsed,
    bufferRetainedBytes: memory.arrayBuffers - heapBefore.arrayBuffers,
    buffersBefore: heapBefore.arrayBuffers,
    buffersAfter: memory.arrayBuffers,
    wasmBytes,
    // What the implementation keeps alive beyond the harness and loaded code.
    retainedBytes: retainedMemory(heapBefore, memory, wasmBytes),
  };
};

/** Loaded code is excluded; collect before I/O and after replay state settles. */
const baseline = async () => {
  const deadline = performance.now() + 1000;
  let previous;
  let stableSince;
  while (performance.now() < deadline) {
    globalThis.gc?.();
    // Loader/native cleanup can outlive several immediate turns. Require real
    // elapsed quiescence so imported transient buffers cannot inflate baseline.
    await new Promise((resolve) => realTimeout(resolve, 10));
    const memory = process.memoryUsage();
    const now = performance.now();
    if (now >= deadline) break;
    if (memory.arrayBuffers !== previous) stableSince = now;
    if (now - stableSince >= 100) return memory;
    previous = memory.arrayBuffers;
  }
  throw new Error('Backing-buffer memory did not settle');
};

