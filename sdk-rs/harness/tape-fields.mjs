// Cookies never belong in persisted public or private replay fixtures.
export function tapeHeaders(value = '') {
  const entries = typeof value === 'string' ? value.split(/\r?\n/).filter(Boolean).map((line) => {
    const at = line.indexOf(':'); return [line.slice(0, at), line.slice(at + 1).trim()];
  }) : value instanceof Headers ? [...value] : Array.isArray(value) ? value : Object.entries(value);
  return entries.filter(([name]) => name.toLowerCase() !== 'set-cookie');
}
