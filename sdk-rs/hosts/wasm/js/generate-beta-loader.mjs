// Writes engine.beta.web.mjs from beta-venues.mjs: literal imports for exactly the
// beta families, so the beta build bundles nothing else and needs no OUT package.
//   node js/generate-beta-loader.mjs            regenerate
//   node js/generate-beta-loader.mjs --families print the family build list
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { betaVenueFamilies } from './beta-venues.mjs';

export const BETA_LOADER = new URL('./engine.beta.web.mjs', import.meta.url);

export function betaLoaderSource() {
  const cases = betaVenueFamilies
    .map((family) => `    case '${family}': return import('../pkg/web/${family}/safe_cex_wasm.js');`)
    .join('\n');
  return `// GENERATED by js/generate-beta-loader.mjs from js/beta-venues.mjs; do not edit.
// The Rust-only beta bundle's web loader: only beta families are importable, and
// an OUT venue is refused by name before any import.
import { betaVenueFamily } from './beta-venues.mjs';
import { familyLoader } from './family-loader.mjs';

function importFamily(family) {
  switch (family) {
${cases}
  }
}

export const loadEngine = familyLoader(importFamily, betaVenueFamily);
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--families')) console.log(betaVenueFamilies.join(' '));
  else writeFileSync(BETA_LOADER, betaLoaderSource());
}
