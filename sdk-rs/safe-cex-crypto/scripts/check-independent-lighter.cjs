const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const {createHash} = require('node:crypto');
const {spawnSync} = require('node:child_process');
const {originalProvenance} = require('./lighter-source-provenance.cjs');
const generator = path.join(__dirname, 'lighter-venue-capture.cjs');
assert.equal(createHash('sha256').update(fs.readFileSync(generator)).digest('hex'), '5cd5d1a8e266eb30a12262c3abb1dd0d28dd6b901e20a37bf99712b6b18f5eb2', 'independent venue generator changed');
const result = spawnSync(process.execPath, [generator], {encoding:'utf8', maxBuffer:4*1024*1024});
assert.equal(result.status, 0, `independent venue capture failed: ${result.stderr}`);
const original = fs.readFileSync(path.join(__dirname, '../tests/fixtures/lighter/venue-signing-preimages.json'), 'utf8');
const normalized = originalProvenance(JSON.parse(result.stdout));
assert.equal(JSON.stringify(normalized, null, 2) + '\n', original, 'independent venue oracle drift');
