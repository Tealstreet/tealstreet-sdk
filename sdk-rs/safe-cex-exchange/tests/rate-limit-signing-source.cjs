const assert=require('node:assert/strict');
const {createRequire}=require('node:module');
const root=createRequire(require('node:path').resolve(__dirname,'../../../package.json'));
const axios=root('axios').default;
const rateLimit=root('axios-rate-limit');
(async()=>{
 let clock=1000;
 const trace=[];
 const late=[];
 const xhr=axios.create({adapter:async config=>{trace.push(['send',config.url,config.headers.get('X-Nonce')]);return {data:{},status:200,headers:{},config};}});
 xhr.interceptors.request.use(config=>{trace.push(['sign',config.url,clock]);config.headers.set('X-Nonce',clock);return config;});
 rateLimit(xhr,{maxRequests:1,perMilliseconds:25});
 xhr.interceptors.request.use(config=>{late.push([config.url,clock]);return config;});
 const first=xhr.get('/first');
 const second=xhr.get('/second');
 await first;
 assert.deepEqual(trace,[['sign','/first',1000],['send','/first','1000']]);
 assert.deepEqual(late,[["/first",1000],["/second",1000]],"later-registered callbacks run before the rate gate");
 clock=2000;
 await second;
 assert.deepEqual(trace,[['sign','/first',1000],['send','/first','1000'],['sign','/second',2000],['send','/second','2000']]);
 console.log(JSON.stringify(trace));
})().catch(error=>{console.error(error);process.exitCode=1;});
