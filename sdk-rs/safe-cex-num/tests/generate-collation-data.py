#!/usr/bin/env python3
"""Regenerate coherent pinned root collation data with an isolated ICU4X tool."""
import hashlib, json, pathlib, subprocess, sys, tempfile
version = subprocess.check_output([sys.argv[1], "--version"], text=True).strip()
if version != "icu4x-datagen 2.3.0":
    raise SystemExit(f"Expected icu4x-datagen 2.3.0, got {version!r}")
crate = pathlib.Path(__file__).resolve().parents[1]
markers = ["CollationRootV1", "CollationDiacriticsV1", "CollationJamoV1", "CollationMetadataV1", "CollationReorderingV1", "CollationSpecialPrimariesV1", "CollationTailoringV1"]
with tempfile.TemporaryDirectory(dir=crate / "../../target") as temporary:
    output = pathlib.Path(temporary) / "data"
    subprocess.run([sys.argv[1], "--format", "baked", "--markers", *markers, "--locales", "und", "--collation-root-han", "unihan", "--cldr-tag", "48.2.1", "--icuexport-tag", "release-78.1rc", "--use-separate-crates", "--no-internal-fallback", "--deduplication", "none", "--out", str(output)], check=True)
    target = crate / "src/collation_data"
    provider = "// @generated by icu4x-datagen 2.3.0; expanded private provider arms.\npub(super) struct RootData;\n"
    for file in sorted(output.glob("*.rs.data")):
        text = file.read_text()
        if text.count("=> { ") < 1 or " } ; ($ provider : ty , ITER)" not in text:
            raise SystemExit(f"Unexpected pinned generator syntax in {file}")
        text = text.split("=> { ", 1)[1].split(" } ; ($ provider : ty , ITER)", 1)[0]
        text = text.replace('# [clippy :: msrv = "1.88"] const _ : () = < $ provider > :: MUST_USE_MAKE_PROVIDER_MACRO ;', "")
        text = text.replace("$ provider", "RootData").replace("pub const", "pub(crate) const")
        provider += text + "\n"
    (target / "provider.rs").write_text(provider)
    checks = {"provider.rs": hashlib.sha256(provider.encode()).hexdigest()}
    profile = {"generator": "icu4x-datagen 2.3.0", "cldr": "48.2.1", "icu": "release-78.1rc", "han": "unihan", "locale": "und", "sha256": checks}
    (target / "profile.json").write_text(json.dumps(profile, indent=2) + "\n")
