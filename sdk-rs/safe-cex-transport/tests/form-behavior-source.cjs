const fs=require('node:fs'),assert=require('node:assert/strict');
const {root,ts}=require('../../safe-cex-types/scripts/accounts-source.cjs');
const source=fs.readFileSync(root+'/packages/http-over-websocket/src/axiosHttpOverWebsocketAdapter.ts','utf8');
const ast=ts.createSourceFile('adapter.ts',source,ts.ScriptTarget.Latest,true);
const fn=ast.statements.find(n=>ts.isFunctionDeclaration(n)&&n.name.text==='parseWebsocketData');
assert.ok(fn,'actual source parser declaration');
const parse=new Function(ts.transpileModule(fn.getText(ast),{compilerOptions:{target:ts.ScriptTarget.ES2022}}).outputText+';return parseWebsocketData;')();
const cases=['__proto__=kept&ok=1','%5F%5Fproto%5F%5F=kept&ok=1','__proto__=kept&__proto__=again&ok=1','constructor=kept&toString=own','ok=1&ok=2','{"__proto__":"kept","ok":1}','raw','%5f%5fproto%5f%5f=x&a=y'];
assert.equal(cases.length,8);
const values=cases.map(data=>parse(JSON.parse,{data}));
for(const i of [0,1,2,7])assert.equal(Object.hasOwn(values[i],'__proto__'),false,'source primitive setter');
assert.equal(Object.hasOwn(values[5],'__proto__'),true,'source JSON own data property');
process.stdout.write(JSON.stringify(values));
