// Source-owned snapshot plus complete typed metadata record, never a projection.
const fs = require('node:fs'), path = require('node:path');
const {load, root, ts} = require('./accounts-source.cjs');
const file = path.join(root,'packages/safe-cex/src/exchangeMetadata.ts');
const source = ts.createSourceFile(file,fs.readFileSync(file,'utf8'),ts.ScriptTarget.Latest,true);
const moduleSource = load(file);
const snake = text => text.replace(/([a-z0-9])([A-Z])/g,'$1_$2').replace(/([A-Z])([A-Z][a-z])/g,'$1_$2').toLowerCase();
const types = {string:'String',number:'f64',boolean:'bool',ExchangeName:'ExchangeName',ExchangeFeatures:'ExchangeFeatures',PositionMode:'PositionMode',MarginType:'MarginType',OrderStopTriggerType:'OrderStopTriggerType',AnyTimeframe:'AnyTimeframe',OrderTimeInForce:'OrderTimeInForce',OrderType:'OrderType'};
const records = new Map(['ExchangeFeatures','ExchangeMetadata'].map(name => [name, source.statements.find(n=>ts.isTypeAliasDeclaration(n)&&n.name.text===name).type]));
function rustType(node, recordName) {
 if(ts.isTypeOperatorNode(node) && node.operator===ts.SyntaxKind.ReadonlyKeyword) return rustType(node.type, recordName);
 if(ts.isArrayTypeNode(node)) return `Vec<${rustType(node.elementType, recordName)}>`;
 if(ts.isUnionTypeNode(node)) {const real=node.types.filter(n=>n.kind!==ts.SyntaxKind.UndefinedKeyword);if(real.length===1)return `Option<${rustType(real[0], recordName)}>`;}
 if(ts.isTypeLiteralNode(node)) {
  if(node.members.length===1 && ts.isIndexSignatureDeclaration(node.members[0])) {
   const index=node.members[0];
   if(index.parameters.length!==1 || index.parameters[0].type.kind!==ts.SyntaxKind.StringKeyword) throw Error('Expected a string-keyed metadata map');
   return `JsObjectMap<${rustType(index.type, recordName)}>`;
  }
  if(!recordName || !node.members.every(ts.isPropertySignature)) throw Error('Expected named metadata fields');
  records.set(recordName,node);
  return recordName;
 }
 const text=node.getText(source);if(!types[text])throw Error(`Unmapped type ${text}`); return types[text];
}
let rust='// Generated by scripts/generate-exchange-metadata.cjs from the live TS source.\nuse crate::{AnyTimeframe, ExchangeName, MarginType, OrderStopTriggerType, OrderTimeInForce, OrderType, PositionMode};\nuse crate::object_map::JsObjectMap;\nuse serde::{Deserialize, Serialize};\n\n';
for(const [name, declaration] of records) {
 let fields='';
 for(const member of declaration.members) {
  const key=member.name.text; let type=rustType(member.type, name+key[0].toUpperCase()+key.slice(1));if(member.questionToken&&!type.startsWith('Option<'))type=`Option<${type}>`;
  fields+=`    #[serde(rename = ${JSON.stringify(key)})]\n`; if(type.startsWith('Option<'))fields+='    #[serde(default, skip_serializing_if = "Option::is_none")]\n';
  fields+=`    pub ${snake(key)}: ${type},\n`;
 }
 rust+='#[derive(Debug, Clone, PartialEq, Serialize)]\npub struct '+name+' {\n'+fields+'}\n\n';
 // Keep Serde field metadata behind the same map guard as other shared records.
 rust+=`#[derive(Deserialize)]\n#[serde(remote = "${name}")]\nstruct ${name}Wire {\n${fields}}\n\n`;
 rust+=`impl<'de> Deserialize<'de> for ${name} {\n    fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {\n        ${name}Wire::deserialize(crate::strict_decode::object(deserializer))\n    }\n}\n\n`;
}
const snapshot={metadata:moduleSource.exchangeMetadata,unified:moduleSource.getExchangeMetadata('bybit',{isUnified:true})};
let native='// Generated direct native field expectations from independent live TS property keys.\nuse safe_cex_types::exchange_metadata::{ExchangeFeatures, ExchangeMetadata};\n';
for(const [name, declaration] of records) {
 native+=`pub fn assert_${snake(name)}_native(native: &${name}, source: &serde_json::Value) {\n`;
 for(const member of declaration.members) {
  const key=member.name.text; let type=rustType(member.type, name+key[0].toUpperCase()+key.slice(1));if(member.questionToken&&!type.startsWith('Option<'))type=`Option<${type}>`;
  if(key==='features')native+=`    assert_exchange_features_native(&native.features, &source["features"]);\n`;
  else native+=`    assert_eq!(native.${snake(key)}, serde_json::from_value::<${type}>(source.get(${JSON.stringify(key)}).cloned().unwrap_or(serde_json::Value::Null)).expect("source field ${key}"), "native ${name}.${key}");\n`;
  if(member.questionToken && ts.isTypeLiteralNode(member.type) && member.type.members.every(ts.isPropertySignature)) native+=`    if let Some(value) = &native.${snake(key)} { assert_${snake(name+key[0].toUpperCase()+key.slice(1))}_native(value, &source[${JSON.stringify(key)}]); }\n`;
 }
 native+='}\n';
}
native=native.replace('use safe_cex_types::exchange_metadata::{ExchangeFeatures, ExchangeMetadata};',`use safe_cex_types::exchange_metadata::{${[...records.keys()].join(', ')}};\nuse safe_cex_types::{AnyTimeframe,ExchangeName,MarginType,PositionMode,OrderStopTriggerType,OrderTimeInForce,OrderType};\nuse safe_cex_types::object_map::JsObjectMap;`);
const formatRust = content => {
 const result=require('node:child_process').spawnSync('rustfmt',['--edition','2024','--emit','stdout'],{input:content,encoding:'utf8'});
 if(result.status!==0)throw Error(result.error?.message || result.stderr);
 return result.stdout;
};
const outputs=[['src/exchange_metadata_generated.rs',formatRust(rust)],['src/exchange_metadata.json',JSON.stringify(snapshot,null,2)+'\n'],['tests/support/exchange_metadata_native.rs',formatRust(native)]];
for(const [name,content] of outputs) {
 const target=path.join(__dirname,'..',name);
 if(process.argv.includes('--check')) {if(fs.readFileSync(target,'utf8')!==content)throw Error(`Stale metadata: ${name}`);} else fs.writeFileSync(target,content);
}
console.log(`metadata: ${Object.keys(snapshot.metadata).length} records; ${source.statements.find(n=>ts.isTypeAliasDeclaration(n)&&n.name.text==='ExchangeMetadata').type.members.length} metadata fields; stopped after the three generated files`);
