const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const test = require('node:test');
const ts = require('typescript');
const { transform } = require('../generate.cjs');
const root = path.resolve(__dirname, '../../..');
const models = path.join(root, 'packages/safe-cex/src/generated');
const names = ['OrderFillEvent', 'Execution', 'PublicTrade'];

// The Order slice owns the enum; its stable public export is the shared identity.
function render(raw, name) {
  return transform(raw, {}, `${name}.ts`, {}).source.replace('from "./OrderSide"', 'from "../types"');
}

test('public execution contracts are the Rust-generated bytes', () => {
  for (const name of names) {
    const raw = fs.readFileSync(path.join(__dirname, '../bindings/raw', `${name}.ts`), 'utf8');
    assert.equal(fs.readFileSync(path.join(models, `${name}.ts`), 'utf8'), render(raw, name));
  }
});

test('execution contracts preserve keys, readonly, optionality and runtime enum identity', () => {
  const fixture = path.join(models, '__execution_contract_check__.ts');
  const source = `
import type { OrderFillEvent as Fill } from './OrderFillEvent';
import type { Execution } from './Execution';
import type { PublicTrade } from './PublicTrade';
import type { OrderFillEvent as OldFill, Execution as OldExecution, PublicTrade as OldTrade } from '../types';
import { OrderSide, PositionSide } from '../types';
type Equal<A, B> = (<T>() => T extends A ? 1 : 2) extends (<T>() => T extends B ? 1 : 2) ? true : false;
type Assert<T extends true> = T;
type Expand<T> = { [K in keyof T]: T[K] };
type FillShape = Assert<Equal<Expand<Fill>, Expand<OldFill>>>;
type ExecutionShape = Assert<Equal<Execution, OldExecution>>;
type TradeShape = Assert<Equal<PublicTrade, OldTrade>>;
type FillKeys = Assert<Equal<keyof Fill, keyof OldFill>>;
type ExecutionKeys = Assert<Equal<keyof Execution, keyof OldExecution>>;
type TradeKeys = Assert<Equal<keyof PublicTrade, keyof OldTrade>>;
declare const f: Fill; declare const oldF: OldFill;
const oldFill: OldFill = f; const generatedFill: Fill = oldF;
declare const e: Execution; declare const oldE: OldExecution;
const oldExecution: OldExecution = e; const generatedExecution: Execution = oldE;
declare const t: PublicTrade; declare const oldT: OldTrade;
const oldTrade: OldTrade = t; const generatedTrade: PublicTrade = oldT;
const fill: Fill = { id:'execution', amount:0, price:0, symbol:'BTC', side:OrderSide.Buy };
fill.orderId = 'order'; fill.realizedPnl = 0; fill.fee = 0;
const execution: Execution = { timestamp:1, symbol:'BTC', price:0, qty:0, side:OrderSide.Sell, positionSide:PositionSide.Long };
const both: Execution = { ...execution, positionSide:'both' };
const trade: PublicTrade = { id:'trade', timestamp:1000, symbol:'BTC', price:0, qty:0, side:OrderSide.Buy };
// @ts-expect-error Event fields inherited from Order remain readonly.
fill.amount = 1;
// @ts-expect-error Execution remains readonly.
execution.commission = 0;
// @ts-expect-error PublicTrade remains readonly.
trade.quoteQty = 0;
// @ts-expect-error Bare strings cannot replace OrderSide.
const stringSide: Fill['side'] = 'buy';
// @ts-expect-error Bare strings cannot replace PositionSide.
const stringLeg: Execution['positionSide'] = 'long';
// @ts-expect-error Explicit null is not an absent fee.
const nullFill: Fill = { ...fill, fee:null };
// @ts-expect-error A missing position leg is distinct from null.
const nullLeg: Execution = { ...execution, positionSide:null };
// @ts-expect-error An unreported quote quantity is distinct from null.
const nullQuote: PublicTrade = { ...trade, quoteQty:null };
// @ts-expect-error A live event is not a historical execution.
const confused: Execution = fill;
// @ts-expect-error PublicTrade requires timestamp.
const missingTrade: PublicTrade = { id:'t', symbol:'BTC', price:1, qty:1, side:OrderSide.Buy };
`;
  const configFile = path.join(root, 'packages/safe-cex/tsconfig.json');
  const config = ts.readConfigFile(configFile, ts.sys.readFile);
  const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, path.dirname(configFile));
  const host = ts.createCompilerHost(parsed.options);
  const original = host.getSourceFile.bind(host);
  host.getSourceFile = (file, version, ...args) => file === fixture
    ? ts.createSourceFile(file, source, version, true) : original(file, version, ...args);
  const program = ts.createProgram([fixture], { ...parsed.options, incremental:false }, host);
  assert.deepEqual(ts.getPreEmitDiagnostics(program).map(d => ts.flattenDiagnosticMessageText(d.messageText, '\n')), []);
});

