const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const test = require('node:test');
const ts = require('typescript');
const root = path.resolve(__dirname, '../../..');
const models = path.join(root, 'packages/safe-cex/src/generated');

test('Market and its option terms are the Rust-generated bytes', () => {
  const publicTypes = fs.readFileSync(path.join(root, 'packages/safe-cex/src/types.ts'), 'utf8');
  assert.doesNotMatch(publicTypes, /export\s+(?:type|interface)\s+(?:Market|OptionTerms|OptionRight)\s*[={]/);
  for (const name of ['Market', 'OptionTerms', 'OptionRight']) {
    assert.equal(fs.readFileSync(path.join(models, `${name}.ts`), 'utf8'),
      fs.readFileSync(path.join(__dirname, '../bindings', `${name}.ts`), 'utf8'));
  }
});

test('Market is bidirectional, deeply readonly, and preserves optional zero-valued terms', () => {
  const fixture = path.join(models, '__market_contract_check__.ts');
  const source = `import type { Market } from './Market';
import type { Market as PublicMarket, OptionGreeks as PublicGreeks } from '../types';
import type { Market as RustMarket } from '${path.join(root, 'sdk-rs/safe-cex-types/bindings/Market')}';
import type { OptionGreeks } from './OptionGreeks';
declare const m: Market;
const publicFromGenerated: PublicMarket = m;
declare const p: PublicMarket;
const generatedFromPublic: Market = p;
declare const r: RustMarket;
const generatedFromRust: Market = r;
const rustFromGenerated: RustMarket = m;
declare const g: OptionGreeks;
const publicGreeks: PublicGreeks = g;
const sharedGreeks: OptionGreeks = publicGreeks;
const minimal: Market = { id: 'native-id', symbol: 'BTCUSDT', base: 'BTC', quote: 'USDT',
 active: false, precision: { amount: 0.01, price: 0.1 },
 limits: { amount: { min: 0, max: 0 }, leverage: { min: 0, max: 0 } } };
const option: NonNullable<Market['option']> = { underlying: 'BTC', expiry: 0, strike: 0,
 right: 'call', style: 'european', settlement: 'cash', premiumAsset: 'USDT', settleAsset: 'USDT' };
`;
  const configFile = path.join(root, 'packages/safe-cex/tsconfig.json');
  const config = ts.readConfigFile(configFile, ts.sys.readFile);
  const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, path.dirname(configFile));
  const host = ts.createCompilerHost(parsed.options);
  const original = host.getSourceFile.bind(host);
  host.getSourceFile = (file, version, ...args) => file === fixture
    ? ts.createSourceFile(file, source, version, true) : original(file, version, ...args);
  const options = { ...parsed.options, incremental: false };
  const program = ts.createProgram([fixture], options, host);
  assert.deepEqual(ts.getPreEmitDiagnostics(program).map(d => ts.flattenDiagnosticMessageText(d.messageText, '\n')), []);
  const invalidSource = source + `m.id = 'other';
m.precision.amount = 1;
m.limits.amount.max = 1;
const badExpiry: NonNullable<Market['option']> = { ...option, expiry: null };
const badRight: NonNullable<Market['option']> = { ...option, right: 'CALL' };
const badMarket: Market = { id: 'x', symbol: 'x', base: 'x', quote: 'x', active: true, precision: { amount: 1, price: 1 } };`;
  host.getSourceFile = (file, version, ...args) => file === fixture
    ? ts.createSourceFile(file, invalidSource, version, true) : original(file, version, ...args);
  const invalid = ts.createProgram([fixture], options, host);
  const errors = ts.getPreEmitDiagnostics(invalid);
  assert.equal(errors.length, 6);
  const messages = errors.map(d => ts.flattenDiagnosticMessageText(d.messageText, '\n'));
  for (const field of ['id', 'amount', 'max']) assert(messages.some(message => message.includes(field) && message.includes('read-only')));
  assert(messages.some(message => message.includes('null')));
  assert(messages.some(message => message.includes('CALL')));
  assert(messages.some(message => message.includes('limits') && message.includes('missing')));
});
