const ts = require('typescript');

const boundaries = {
  ExchangeName: '../types',
  RemoteSigner: '../types',
  PayloadSigner: '../types',
  PublicDataSource: '../types',
  TransportProvider: '../transport/types',
  LocalSignerMetadata: '@tealstreet/safe-cex-wasm/host',
  RustPublicFeedPolicy: '../exchanges/rust/publicFeed',
};

function renderOptions(name, raw, transformSource = require('../generate.cjs').transform) {
  raw = raw.replace(/^\/\/ This file was generated[^\n]*\n/, '');
  const parsed = ts.createSourceFile(`${name}.ts`, raw, ts.ScriptTarget.Latest, true);
  const declaration = parsed.statements.find(node => ts.isTypeAliasDeclaration(node) && node.name.text === name);
  if (!declaration) throw new Error(`missing Rust declaration: ${name}`);
  const plain = ts.createPrinter().printNode(ts.EmitHint.Unspecified, declaration, parsed);
  const source = plain.replace(/^(?:export\s+)?type\s+/, 'export type ');
  const references = new Set();
  function visit(node) {
    if (ts.isTypeReferenceNode(node) && ts.isIdentifier(node.typeName)) references.add(node.typeName.text);
    ts.forEachChild(node, visit);
  }
  visit(declaration);
  const imports = Object.entries(boundaries).filter(([type]) => references.has(type))
    .map(([type, module]) => `import type { ${type} } from '${module}';`).join('\n');
  return '// This file was generated by [ts-rs](https://github.com/Aleph-Alpha/ts-rs). Do not edit this file manually.\n'
    + (imports ? `${imports}\n` : '') + transformSource(source, {}, `${name}.ts`).source;
}

module.exports = { renderOptions };
