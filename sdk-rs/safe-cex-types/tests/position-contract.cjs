const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const test = require('node:test');
const ts = require('typescript');
const root = path.resolve(__dirname, '../../..');
const models = path.join(root, 'packages/safe-cex/src/generated');

test('public Position and its complete dependency closure are the Rust-generated bytes', () => {
  const visited = new Set();
  function visit(name) {
    if (visited.has(name)) return;
    visited.add(name);
    const source = fs.readFileSync(path.join(models, `${name}.ts`), 'utf8');
    assert.equal(source, fs.readFileSync(path.join(__dirname, '../bindings', `${name}.ts`), 'utf8'));
    const ast = ts.createSourceFile(`${name}.ts`, source, ts.ScriptTarget.Latest, true);
    for (const statement of ast.statements) {
      if (ts.isImportDeclaration(statement)) visit(statement.moduleSpecifier.text.slice(2));
    }
  }
  visit('Position');
  const publicTypes = fs.readFileSync(path.join(root, 'packages/safe-cex/src/types.ts'), 'utf8');
  assert.doesNotMatch(publicTypes, /export\s+(?:type|interface)\s+Position\s*[={]/);
  assert.doesNotMatch(publicTypes, /export\s+enum\s+(?:PositionSide|PositionMode|MarginType)\b/);
});

test('the generated public contract requires nullable liquidation, readonly and runtime enums', () => {
  const fixture = path.join(models, '__position_contract_check__.ts');
  const source = `import { Position, PositionSide, PositionMode, MarginType } from '../types';
import type { Position as RustPosition } from '${path.join(root, 'sdk-rs/safe-cex-types/bindings/Position')}';
declare const rustPosition: RustPosition;
const publicFromRust: Position = rustPosition;
declare const publicPosition: Position;
const rustFromPublic: RustPosition = publicPosition;
const p: Position = { id: 'p', symbol: 'BTC', side: PositionSide.Long, entryPrice: 1,
 notional: 1, leverage: 1, unrealizedPnl: 0, contracts: 1, liquidationPrice: null,
 marginType: MarginType.Cross, positionMode: PositionMode.OneWay };
const n: number | null = p.liquidationPrice;
const unknownNotional: Position = { ...p, notional: null };
const notional: number | null = p.notional;
const unsafeNotional: number = p.notional;
const unsafe: number = p.liquidationPrice;
p.contracts = 2;
const side: Position['side'] = 'long';
const missing: Position = { id: 'p', symbol: 'BTC', side: PositionSide.Long, entryPrice: 1, notional: 1, leverage: 1, unrealizedPnl: 0, contracts: 1 };
const missingNotional: Position = { id: 'p', symbol: 'BTC', side: PositionSide.Long, entryPrice: 1, leverage: 1, unrealizedPnl: 0, contracts: 1, liquidationPrice: null };
`;
  const configFile = path.join(root, 'packages/safe-cex/tsconfig.json');
  const config = ts.readConfigFile(configFile, ts.sys.readFile);
  const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, path.dirname(configFile));
  const host = ts.createCompilerHost(parsed.options);
  const original = host.getSourceFile.bind(host);
  host.getSourceFile = (file, version, ...args) => file === fixture
    ? ts.createSourceFile(file, source, version, true) : original(file, version, ...args);
  const program = ts.createProgram([fixture], { ...parsed.options, incremental: false }, host);
  const diagnostics = ts.getPreEmitDiagnostics(program);
  // These invalid uses must fail without suppressing compiler diagnostics.
  // This also fails on unexpected dependency errors or a weakened public type.
  const lineOf = text => source.slice(0, source.indexOf(text)).split('\n').length;
  assert.deepEqual(diagnostics.map(d => ({
    file: d.file?.fileName,
    code: d.code,
    line: d.file && d.start !== undefined
      ? d.file.getLineAndCharacterOfPosition(d.start).line + 1 : undefined,
  })), [
    { file: fixture, code: 2322, line: lineOf('const unsafeNotional:') },
    { file: fixture, code: 2322, line: lineOf('const unsafe:') },
    { file: fixture, code: 2540, line: lineOf('p.contracts =') },
    { file: fixture, code: 2322, line: lineOf('const side:') },
    { file: fixture, code: 2741, line: lineOf('const missing:') },
    { file: fixture, code: 2741, line: lineOf('const missingNotional:') },
  ]);
});
