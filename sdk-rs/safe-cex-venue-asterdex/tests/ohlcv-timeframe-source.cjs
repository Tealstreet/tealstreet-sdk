const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const vm = require('node:vm');
const ts = require(process.env.SAFE_CEX_TYPESCRIPT_PATH || 'typescript');
const source = fs.readFileSync(path.resolve(__dirname, '../../../packages/safe-cex/src/exchanges/asterdex/asterdex.exchange.ts'), 'utf8');
const ast = ts.createSourceFile('asterdex.exchange.ts', source, ts.ScriptTarget.Latest, true);
const owner = ast.statements.find(n => ts.isClassDeclaration(n) && n.name?.text === 'AsterDEXExchange');
const method = owner.members.find(n => n.name?.getText(ast) === 'mapTimeframe');
assert(method?.body, 'OHLCV-ASTER maintained mapTimeframe method');
const js = ts.transpileModule(`class Probe { ${method.getText(ast)} }; globalThis.probe = new Probe();`, {compilerOptions:{target:ts.ScriptTarget.ES2022}}).outputText;
const context = vm.createContext({}); vm.runInContext(js, context);
const base = ['1m','3m','5m','15m','30m','1h','2h','4h','6h','12h','1d','1w'];
const extended = ['1M','1s','5s','15s','30s','3h','5h','7h','8h','9h','10h','11h','24h','2d','3d'];
const records = [...base,...extended].map(interval => {
  const result = context.probe.mapTimeframe(interval);
  assert.equal(result, base.includes(interval) ? interval : '1h', `OHLCV-ASTER source ${interval}`);
  return {interval,result};
});
assert.equal(records.length,27);
process.stdout.write(JSON.stringify(records));
