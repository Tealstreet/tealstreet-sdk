const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require(process.env.SAFE_CEX_TYPESCRIPT_PATH || 'typescript');
const root = path.resolve(__dirname, '../../../packages/safe-cex/src');
const parse = file => ts.createSourceFile(file, fs.readFileSync(path.join(root, file), 'utf8'), ts.ScriptTarget.Latest, true);
const declaration = (tree, name) => {
  const node = tree.statements.find(n => ts.isVariableStatement(n) && n.declarationList.declarations.some(d => d.name.getText(tree) === name));
  assert.ok(node, `maintained declaration ${name}`);
  return node.getText(tree).replace(/^export /, '');
};
const compile = text => ts.transpileModule(text, { compilerOptions: {module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, esModuleInterop: true} }).outputText;
(async () => {
  const input = JSON.parse(fs.readFileSync(0, 'utf8'));
  const stem = input.pm ? 'binancepm' : 'binance';
  const tree = parse(`exchanges/binance/${stem}.exchange.ts`);
  const cls = tree.statements.find(ts.isClassDeclaration);
  const method = input.pm ? 'fetchRegularOrders' : 'fetchOrders';
  const member = cls.members.find(m => m.name?.getText(tree) === method);
  assert.ok(member, `maintained ${method}`);
  const types = parse(`exchanges/binance/${stem}.types.ts`);
  const shared = parse('types.ts');
  const severityFile = path.resolve(root, '../../logging/src/LogSeverity.ts');
  const severity = ts.createSourceFile(severityFile, fs.readFileSync(severityFile, 'utf8'), ts.ScriptTarget.Latest, true);
  const math = parse('utils/safe-math.ts');
  const baseTree = parse('exchanges/base.ts');
  const base = baseTree.statements.find(n => ts.isClassDeclaration(n) && n.name?.text === 'BaseExchange');
  const log = base.members.find(n => n.name?.getText(baseTree) === 'log');
  assert.ok(log, 'maintained BaseExchange.log');
  const tables = ['ENDPOINTS', 'ORDER_TYPE', 'ORDER_SIDE', 'ORDER_TRIGGER_TYPE'].map(name => declaration(types, name)).join('\n');
  const helpers = input.pm ? ['describeBinancePMResponseShape', 'getBinancePMResponseMessage', 'requireBinancePMArrayResponse'].map(name => declaration(tree, name)).join('\n') : '';
  const context = vm.createContext({exports: {}, require, virtualClock: {getCurrentTimeMs: () => 10000}});
  const notices = [];
  context.console = {error: (...args) => notices.push(['console', ...args]), log() {}};
  vm.runInContext(compile(shared.statements.filter(ts.isEnumDeclaration).map(n => n.getText(shared)).join('\n') + '\n' + severity.statements.filter(ts.isEnumDeclaration).map(n => n.getText(severity)).join('\n') + '\n' + tables + '\n' + helpers + '\n' + [declaration(math, 'POW10_CACHE'), math.statements.find(ts.isForStatement).getText(math), declaration(math, 'pow10'), declaration(math, 'afterDecimal'), declaration(math, 'subtract')].join('\n') + `\nexports.Subject=class {${member.getText(tree)} ${log.getText(baseTree)}};`), context);
  const keys = {exports: {}, require};
  vm.runInNewContext(compile(fs.readFileSync(path.join(root, 'utils/get-key.ts'), 'utf8')), keys);
  context.v = keys.exports.v;
  context.subtract = context.exports.subtract;
  const subject = new context.exports.Subject();
  const payload = JSON.parse(input.raw);
  subject.xhr = {get: async endpoint => ({data: endpoint.toLowerCase().includes('algo') ? [] : payload})};
  subject.papiXhr = {get: async () => ({data: payload})};
  subject.store = {orders: []};
  subject.name = input.pm ? 'binancepm' : 'binance';
  subject.options = {tuning: {consoleLogging: false}};
  subject.emitter = {emit: (event, ...args) => notices.push([event, ...args])};
  subject.emitAndLogError = (...args) => notices.push(['emit', ...args]);
  const units = value => Array.from({length: value.length}, (_, i) => value.charCodeAt(i));
  let output;
  try {
    const rows = await subject[method]();
    output = {rows: rows.length, log: notices.filter(n => n[0] === 'log').map(n => units(n[1])), errors: notices.filter(n => n[0] === 'emit').length};
    if (rows.length) output.info = units(rows[0].info[0]);
  } catch (error) {output = {name: error.name, message: units(error.message)};}
  process.stdout.write(JSON.stringify(output));
})().catch(error => {console.error(error); process.exitCode = 1;});
