import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createHmac} from 'node:crypto';
import vm from 'node:vm';
import ts from 'typescript';
const family=process.argv[2]??'bybit';
assert(['bybit','bybitinverse','bybitspot'].includes(family));
const source=ts.createSourceFile('private.ts',readFileSync(new URL(`../../../packages/safe-cex/src/exchanges/bybit/${family}.ws-private.ts`,import.meta.url),'utf8'),ts.ScriptTarget.Latest,true);
const owner=source.statements.find(n=>ts.isClassDeclaration(n)&&n.name?.text===(family==='bybitinverse'?'BybitInversePrivateWebsocket':'BybitPrivateWebsocket'));
const names=['onOpen','sendReconnectSequence','auth','subscribe','ping'];
const members=owner.members.filter(m=>names.includes(m.name?.getText(source)));
assert.equal(members.length,names.length);
const results=[];
for(const mode of ['local','signed','missing','error']) for(const disposed of [false,true]) {
 const messages=[], errors=[], requests=[], sleeps=[];let release;let syncCalls=0;
 const context=vm.createContext({Error,createHmac,nanoid:()=> 'fixture',ENABLE_RECONNECTING_WEBSOCKET:false,performance:{now:()=>1000},sleep:async n=>{sleeps.push(n);},virtualClock:{getCurrentTimeMs:()=>1000,syncBybitClientServerTime:()=>{syncCalls++;return new Promise(r=>release=r);}}});
 vm.runInContext(ts.transpileModule(`class Subject {${members.map(m=>m.getText(source)).join('\n')}};globalThis.subject=new Subject();`,{compilerOptions:{target:ts.ScriptTarget.ES2022}}).outputText,context);
 const response=mode==='signed'?{wsAuthSignature:'signed'}:mode==='error'?{error:'unpaired'}:{};
 const subject=context.subject;
 subject.isDisposed=disposed;
 subject.parent={options:{key:'fixture-key',secret:'secret',...(mode==='local'?{}:{remoteSigner:{accountName:'account',sign:async request=>{requests.push(request);return response;}}})}};
 subject.sendWithLog=message=>{if(!subject.isDisposed)messages.push(message);};
 subject.emitAndLogError=error=>errors.push(error.message??error);
 let disregards=0,reconnects=0;
 subject.directFallback={disregardSilence:()=>disregards++};subject.reconnect=()=>reconnects++;
 const sequence=subject.sendReconnectSequence;let pending;
 subject.sendReconnectSequence=(...args)=>{pending=sequence(...args);return pending;};
 const returned=subject.onOpen();assert.equal(returned,undefined,'onOpen does not return sequence promise');
 const before={syncCalls,messages:[...messages],requests:[...requests]};release?.();await pending;
 results.push({mode,disposed,response,before,messages,requests,errors,sleeps,disregards,reconnects});
}
assert.equal(results.length,8);process.stdout.write(JSON.stringify(results));
