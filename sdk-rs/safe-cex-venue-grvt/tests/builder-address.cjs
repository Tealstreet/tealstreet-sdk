'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require(process.env.SAFE_CEX_TYPESCRIPT_PATH);
const deps = process.env.SAFE_CEX_CRYPTO_ORACLE_DEPS;
assert(deps && path.isAbsolute(deps), 'absolute crypto oracle installation required');
const oracleRequire = require('node:module').createRequire(path.join(deps, 'package.json'));
const resolved = fs.realpathSync(oracleRequire.resolve('ethers'));
assert(resolved.startsWith(fs.realpathSync(deps) + path.sep), 'ethers must resolve inside declared installation');
const ethers = oracleRequire('ethers');
assert.equal(ethers.version, '6.17.0', 'builder ethers version');
const file = path.resolve(__dirname, '../../../packages/safe-cex/src/exchanges/grvt/grvt.builder.ts');
const text = fs.readFileSync(file, 'utf8');
const tree = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true);
const names = ['getStringField', 'getValidAddress'];
const statements = names.map(name => {
  const found = tree.statements.filter(s => ts.isVariableStatement(s) && s.declarationList.declarations.some(d => d.name.getText(tree) === name));
  assert.equal(found.length, 1, `actual declaration ${name}`);
  return found[0].getText(tree);
});
let source = statements.join('\n');
if (process.env.GRVT_ADDRESS_MUTATION === 'last') {
  assert(source.includes('values.find('), 'source selection mutation match');
  source = source.replace('values.find(', 'values.findLast(');
} else assert(!process.env.GRVT_ADDRESS_MUTATION, 'unknown mutation');
const compiled = ts.transpileModule(source + '\nexports.pick = getValidAddress; exports.field = getStringField;', {compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS},reportDiagnostics:true});
assert.equal(compiled.diagnostics.length, 0);
const context = {exports:{}, isAddress:ethers.isAddress};
vm.runInNewContext(compiled.outputText, context);
const a = '0x52908400098527886E0F7030069857D2E4169EE7';
const b = '0xde709f2102306220921060314715629080e2fb77';
const icap = ethers.getIcapAddress(a);
const candidates = [null, '', 'invalid', a, b, a.toLowerCase(), a.slice(2), '0X' + a.slice(2), a.replace('E0F', 'e0F'), icap, icap.slice(0,-1) + (icap.endsWith('0') ? '1' : '0')];
const lists = [[], ...candidates.map(x => [x])];
for (const x of candidates) for (const y of candidates) for (const z of candidates) lists.push([x,y,z]);
const addresses = lists.map(input => ({input, expected:context.exports.pick(...input.map(x=>x===null?undefined:x)) ?? null}));
const inputs = [null, false, true, 0, 1.25, '', 'alpha', 'beta', '😀', [], {}, {value:'text'}];
const fields = [{present:false,input:null,expected:context.exports.field(undefined) ?? null}, ...inputs.map(input=>({present:true,input,expected:context.exports.field(input) ?? null}))];
const surrogates = ['"\\ud800"','"\\udfff"','"a\\ud800b"'].map(raw => {
  const value = context.exports.field(JSON.parse(raw));
  return {raw, units:Array.from({length:value.length},(_,i)=>value.charCodeAt(i)), addressOnly:context.exports.pick(undefined,value) ?? null, beforeValid:context.exports.pick(value,a) ?? null};
});
process.stdout.write(JSON.stringify({architecture:process.arch,node:process.versions.node,ethers:ethers.version,addresses,fields,surrogates}));
