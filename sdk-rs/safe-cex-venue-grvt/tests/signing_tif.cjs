const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const compiler=process.env.SAFE_CEX_TYPESCRIPT_PATH;
assert(compiler&&path.isAbsolute(compiler),'absolute isolated compiler required');
const ts=require(compiler);
process.stderr.write(JSON.stringify({captureArchitecture:process.arch,node:process.version})+'\n');
const dir=path.resolve(__dirname,'../../../packages/safe-cex/src/exchanges/grvt');
const file=path.join(dir,'grvt.exchange.ts');
const tree=ts.createSourceFile(file,fs.readFileSync(file,'utf8'),ts.ScriptTarget.Latest,true);
const cls=tree.statements.find(s=>ts.isClassDeclaration(s)&&s.name.text==='GrvtExchange');
const method=cls.members.find(s=>s.name?.getText(tree)==='mapTimeInForceToEnum');
assert(method?.body,'actual signing TIF method');
const types=ts.createSourceFile('types.ts',fs.readFileSync(path.join(dir,'grvt.types.ts'),'utf8'),ts.ScriptTarget.Latest,true);
const union=types.statements.find(s=>ts.isTypeAliasDeclaration(s)&&s.name.text==='GrvtTimeInForce');
assert(union&&ts.isUnionTypeNode(union.type),'closed TIF union');
const keys=union.type.types.map(t=>{assert(ts.isLiteralTypeNode(t)&&ts.isStringLiteral(t.literal),'closed string member');return t.literal.text;});
assert.equal(keys.length,4,'signing TIF source census');
let body=method.body.getText(tree);
if(process.env.GRVT_SIGNING_TIF_CONTROL==='zero-base') {assert(body.includes('GOOD_TILL_TIME: 1'));body=body.replace('GOOD_TILL_TIME: 1','GOOD_TILL_TIME: 0');}
const context={exports:{}};
vm.runInNewContext(ts.transpileModule('export function measured(timeInForce: any) '+body,{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,context);
process.stdout.write(JSON.stringify(keys.map(key=>({key,value:context.exports.measured(key)}))));
