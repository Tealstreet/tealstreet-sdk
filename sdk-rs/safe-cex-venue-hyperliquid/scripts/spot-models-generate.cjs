// Deterministic model/projection writer. The oracle computes expectations from
// the actual TypeScript separately; native projections never use model serde.
const fs=require('node:fs'), path=require('node:path'), assert=require('node:assert/strict');
const ts=require(process.env.SAFE_CEX_TYPESCRIPT_PATH||'typescript');
const root=path.resolve(__dirname,'../../..'), crate=path.resolve(__dirname,'..');
const sourcePath=path.join(root,'packages/safe-cex/src/exchanges/hyperliquid/hyperliquidspot.types.ts');
const source=ts.createSourceFile(sourcePath,fs.readFileSync(sourcePath,'utf8'),ts.ScriptTarget.Latest,true);
require('./interface-heritage.cjs')(ts,source);
const ROOTS=['WsFill','WsUserFunding','WsLiquidation','WsNonUserCancel'];
assert.equal(ROOTS.length,4);
const shapes=new Map(), declarations=new Map();
for(const statement of source.statements) if(ts.isInterfaceDeclaration(statement)||ts.isTypeAliasDeclaration(statement)) {
  const name=statement.name.text;
  if(ts.isInterfaceDeclaration(statement)) {
    const old=declarations.get(name);
    if(old) {assert.equal(old.getText(source),statement.getText(source),`same merged interface ${name}`);continue;}
  }
  declarations.set(name,statement);
}
const pascal=text=>text.replace(/(^|[_:-])(\w)/g,(_,p,c)=>c.toUpperCase());
const snake=text=>text.length===1&&text.toUpperCase()===text?text.toLowerCase()+'_upper':text.replace(/([a-z0-9])([A-Z])/g,'$1_$2').toLowerCase();
const field=name=>['type','ref','self'].includes(snake(name))?'r#'+snake(name):snake(name);
const q=JSON.stringify;
function record(name,members) {
  assert(!shapes.has(name),`unique record ${name}`);
  const fields=members.map(member=> {
    assert(ts.isPropertySignature(member));
    return {name:member.name.text,optional:!!member.questionToken,type:type(member.type,name+pascal(member.name.text))};
  });
  const shape={kind:'record',name,fields};shapes.set(name,shape);return shape;
}
function type(node,name) {
  if(ts.isParenthesizedTypeNode(node))return type(node.type,name);
  if(ts.isTypeReferenceNode(node)) {
    const ref=node.typeName.getText(source);
    return ref==='Array'?{kind:'array',item:type(node.typeArguments[0],name+'Item')}:{kind:'ref',name:ref};
  }
  if(ts.isArrayTypeNode(node))return {kind:'array',item:type(node.elementType,name+'Item')};
  if(ts.isTupleTypeNode(node))return {kind:'tuple',items:node.elements.map((item,index)=>type(item,name+'Item'+index))};
  if(ts.isTypeLiteralNode(node))return record(name,node.members);
  if(ts.isLiteralTypeNode(node)&&ts.isStringLiteral(node.literal)) {
    const shape={kind:'enum',name,values:[node.literal.text]};shapes.set(name,shape);return shape;
  }
  if(ts.isUnionTypeNode(node)&&node.types.every(item=>ts.isLiteralTypeNode(item)&&ts.isStringLiteral(item.literal))) {
    const shape={kind:'enum',name,values:node.types.map(item=>item.literal.text)};shapes.set(name,shape);return shape;
  }
  if(node.kind===ts.SyntaxKind.StringKeyword)return {kind:'string'};
  if(node.kind===ts.SyntaxKind.NumberKeyword)return {kind:'number'};
  if(node.kind===ts.SyntaxKind.BooleanKeyword)return {kind:'bool'};
  throw Error(`unsupported ${ts.SyntaxKind[node.kind]} ${name}`);
}
for(const name of ROOTS) {
  const declaration=declarations.get(name);assert(declaration,`actual source declaration ${name}`);
  const result=ts.isInterfaceDeclaration(declaration)?record(name,declaration.members):type(declaration.type,name);
  if(result.name!==name)shapes.set(name,{kind:'alias',name,target:result});
}
function rust(shape) {
  switch(shape.kind) {
    case 'string':return 'JsString';case 'number':return 'f64';case 'bool':return 'bool';
    case 'ref':return shape.name;
    case 'record':case 'enum':return shape.name;
    case 'array':return `Vec<${rust(shape.item)}>`;
    case 'tuple':return shape.items.length===2&&shape.items.every(item=>item.kind==='number')?'[f64; 2]':`(${shape.items.map(rust).join(', ')},)`;
    default:throw Error(shape.kind);
  }
}
function decoder(shape,optional) {
  assert(!(optional&&shape.kind==='number'),'no optional number in current scope');
  assert(shape.kind!=='tuple','no tuple in current scope');
  if(shape.kind==='number')return 'number';
  return optional?'present':null;
}
let code='//! Declared spot wire models from hyperliquidspot.types.ts.\n//! Generated by scripts/spot-models-generate.cjs; keep native field mapping.\n//! Raw JSON string/slice ingress retains UTF-16 and binary64; no Value ingress claim.\nuse crate::spot_json::JsString;\nuse serde::{Deserialize, Serialize};\n\n';
for(const shape of shapes.values()) {
  const name=shape.name;
  if(shape.kind==='alias'){code+=`pub type ${name} = ${rust(shape.target)};\n\n`;continue;}
  if(shape.kind==='enum') {
    code+=`#[derive(Debug, Clone, PartialEq, Serialize)]\npub enum ${name} {\n${shape.values.map(value=>`#[serde(rename=${q(value)})]\n${pascal(value)},`).join('\n')}\n}\nimpl<'de> Deserialize<'de> for ${name} {\nfn deserialize<D: serde::Deserializer<'de>>(decoder: D) -> Result<Self,D::Error> {\nlet raw=Box::<serde_json::value::RawValue>::deserialize(decoder)?;\nlet units=crate::spot_json::string_token(raw.get()).map_err(serde::de::Error::custom)?;\n${shape.values.map(value=>`if units==${q(value)}.encode_utf16().collect::<Vec<_>>() { return Ok(Self::${pascal(value)}); }`).join('\n')}\nErr(serde::de::Error::custom("invalid closed spot literal"))\n}\n}\n\n`;
    continue;
  }
  const definition=shape.fields.map(member=>`pub ${field(member.name)}: ${member.optional?'Option<'+rust(member.type)+'>':rust(member.type)},`).join('\n');
  const wire=shape.fields.map(member=> {
    const custom=decoder(member.type,member.optional);
    const attributes=[`rename=${q(member.name)}`];
    if(member.optional)attributes.push('default','skip_serializing_if="Option::is_none"');
    if(custom)attributes.push(`deserialize_with="crate::spot_json::${custom}"`);
    return `#[serde(${attributes.join(', ')})]\npub ${field(member.name)}: ${member.optional?'Option<'+rust(member.type)+'>':rust(member.type)},`;
  }).join('\n');
  code+=`#[derive(Debug, Clone, PartialEq)]\npub struct ${name} {\n${definition}\n}\n#[derive(Serialize, Deserialize)]\n#[serde(remote=${q(name)})]\nstruct ${name}Wire {\n${wire}\n}\nimpl Serialize for ${name} {\nfn serialize<S:serde::Serializer>(&self, encoder:S)->Result<S::Ok,S::Error> { ${name}Wire::serialize(self,encoder) }\n}\nimpl<'de> Deserialize<'de> for ${name} {\nfn deserialize<D:serde::Deserializer<'de>>(decoder:D)->Result<Self,D::Error> {\nstruct OnlyMap;\nimpl<'de> serde::de::Visitor<'de> for OnlyMap {\ntype Value=${name};\nfn expecting(&self,f:&mut std::fmt::Formatter<'_>)->std::fmt::Result { f.write_str("a spot object record") }\nfn visit_map<A:serde::de::MapAccess<'de>>(self,map:A)->Result<Self::Value,A::Error> { ${name}Wire::deserialize(serde::de::value::MapAccessDeserializer::new(map)) }\n}\nlet raw=Box::<serde_json::value::RawValue>::deserialize(decoder)?;\nlet object=crate::spot_json::object_fields(raw.get(),&[${shape.fields.map(member=>q(member.name)).join(",")}]).map_err(serde::de::Error::custom)?;\nlet mut decoder=serde_json::Deserializer::from_str(&object);\nserde::Deserializer::deserialize_map(&mut decoder,OnlyMap).map_err(serde::de::Error::custom)\n}\n}\n\n`;
}
function projection(shape,expression) {
  switch(shape.kind) {
    case 'number':return `number(${expression})`;
    case 'bool':return `serde_json::json!(${expression})`;
    case 'string':return `serde_json::json!((${expression}).0)`;
    case 'ref':case 'record':case 'enum':return `(${expression}).native()`;
    case 'array':return `Value::Array((${expression}).iter().map(|item| ${projection(shape.item,'item')}).collect())`;
    case 'tuple': {
      const pair=shape.items.every(item=>item.kind==='number');
      return `Value::Array(vec![${shape.items.map((item,index)=>projection(item,pair?`&(${expression})[${index}]`:`&(${expression}).${index}`)).join(', ')}])`;
    }
    default:throw Error(shape.kind);
  }
}
let native='// Generated direct native projections; no model Serialize/roundtrip.\n';
for(const shape of shapes.values()) {
  if(shape.kind==='alias')continue;
  const name=shape.name;
  let body;
  if(shape.kind==='enum')body=`match self {${shape.values.map(value=>`Self::${pascal(value)}=>serde_json::json!(${q(value)})`).join(', ')}}`;
  else body=`Value::Object([${shape.fields.map(member=> {
    const value=projection(member.type,'&self.'+field(member.name));
    return `(${q(member.name)}.into(),${member.optional?`self.${field(member.name)}.as_ref().map(|value| ${projection(member.type,'value')}).unwrap_or_else(|| serde_json::json!({"absent":true}))`:value})`;
  }).join(', ')}].into_iter().collect())`;
  native+=`impl Native for ${name} { fn native(&self)->Value {${body}} }\n`;
}
// Root aliases use shared Native implementations for JsString/Vec; root names
// are enumerated independently in the test driver.
const dispatch=ROOTS.map(name=>`${q(name)}=>check::<${name}>(row),`).join('\n');
const outputs={
  'src/spot_models.rs':code,
  'tests/fixtures/spot-model-native.rs':native,
  'tests/fixtures/spot-model-dispatch.rs':`fn dispatch(row:&Value) { match row["name"].as_str().unwrap() {${dispatch}\nother=>panic!("unknown spot root {other}"),} }\n`,
};
if(require.main===module) {
  const child=require('node:child_process');
  for(const [name,text] of Object.entries(outputs)) {
    const formatted=child.execFileSync('rustfmt',['--edition','2021','--emit','stdout'],{input:text,encoding:'utf8'});
    if(process.argv.includes('--check'))assert.equal(fs.readFileSync(path.join(crate,name),'utf8'),formatted,'generated spot model drift '+name);
    else fs.writeFileSync(path.join(crate,name),formatted);
  }
  console.log(`wrote ${ROOTS.length} source roots, ${shapes.size} native/alias declarations and direct field projections`);
}
module.exports={ROOTS,shapes,declarations,source};
