const fs = require('node:fs');
const path = require('node:path');
const ts = require(process.env.SAFE_CEX_TYPESCRIPT_PATH || 'typescript');
const source = fs.readFileSync(path.resolve(__dirname, '../../../packages/safe-cex/src/exchanges/kucoin/kucoinspot.types.ts'), 'utf8');
const parsed = ts.createSourceFile('source.ts', source, ts.ScriptTarget.Latest, true);
const declarations = parsed.statements.filter(node => ts.isTypeAliasDeclaration(node)).map(node => node.getText(parsed)).join('\n');
const cases = JSON.parse(fs.readFileSync(0, 'utf8'));
const preamble = declarations + '\n';
const assignments = cases.map((item, i) => `const input${i} = ${JSON.stringify(item.value)}; const case${i}: ${item.type} = input${i};\n`);
const text = preamble + assignments.join('');
const filename = path.resolve(__dirname, 'virtual-records.ts');
const options = { strict: true, noEmit: true, target: ts.ScriptTarget.ES2022 };
const host = ts.createCompilerHost(options);
const original = host.getSourceFile.bind(host);
host.getSourceFile = (file, languageVersion, ...args) => file === filename ? ts.createSourceFile(file, text, languageVersion, true) : original(file, languageVersion, ...args);
const program = ts.createProgram([filename], options, host);
const diagnostics = ts.getPreEmitDiagnostics(program);
const invalidPreamble = diagnostics.filter(d => d.file?.fileName !== filename || d.start < preamble.length);
if (invalidPreamble.length) throw new Error(ts.formatDiagnosticsWithColorAndContext(invalidPreamble, {getCurrentDirectory:()=>process.cwd(),getCanonicalFileName:x=>x,getNewLine:()=> '\n'}));
let start = preamble.length;
const accepted = assignments.map(statement => {
 const end = start + statement.length;
 const valid = !diagnostics.some(d => d.start >= start && d.start < end);
 start = end;
 return valid;
});
process.stdout.write(JSON.stringify(accepted));
