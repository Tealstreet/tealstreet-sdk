import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {root,ts,load} from './source.mjs';
const file=root+'packages/safe-cex/src/exchanges/mexc/mexc.ws-public.ts';
const source=fs.readFileSync(file,'utf8');
const ast=ts.createSourceFile(file,source,ts.ScriptTarget.Latest,true);
const owner=ast.statements.find(n=>ts.isClassDeclaration(n)&&n.name?.text==='MexcPublicWebsocket');
const methods=['onMessage','handleTicker'].map(name=>{const member=owner.members.find(n=>n.name?.getText(ast)===name);assert(member,'SOURCE public route member '+name);return member.getText(ast);});
const utils=load('packages/safe-cex/src/exchanges/mexc/mexc.utils.ts');
const {DefaultStore}=load('packages/safe-cex/src/store/store.base.ts');
const {isMexcControlChannel}=load('packages/safe-cex/src/exchanges/mexc/mexc.types.ts');
const {bigIntAsStringJsonParse}=load('packages/json-parse/src/jsonParse.ts');
const ctx={...utils,isMexcControlChannel,bigIntAsStringJsonParse,LogSeverity:{Warning:'warning'}};
vm.runInNewContext(ts.transpileModule('class Holder{'+methods.join('\n')+'}\nglobalThis.Holder=Holder;',{compilerOptions:{target:ts.ScriptTarget.ES2022}}).outputText,ctx);
const store=new DefaultStore();
const market=utils.normalizeMarket({symbol:'BTC_USDT',contractSize:.5,maxLeverage:20});
const ticker=utils.normalizeTicker({symbol:'BTC_USDT',lastPrice:17,bid1:16,ask1:18},market);
store.update({markets:[market],tickers:[ticker]},false);
const origin=Object.assign(new Error('public subscriber origin'),{code:313});
let first=0,later=0;
store.subscribe(()=>{first++;throw origin;});
store.subscribe(()=>{later++;});
const holder=new ctx.Holder();
Object.assign(holder,{store,isDisposed:false,trackLastReceived(){},emitReceiveDiagnostics(){},recordMessageHandlerStats(){}});
let error;
try{holder.onMessage({data:JSON.stringify({channel:'push.ticker',symbol:'BTC_USDT',data:{lastPrice:29,bid1:28,ask1:30}})});}catch(e){error=e;}
assert.equal(store.tickers[0].last,29,'SOURCE public route committed price');
assert.equal(first,1,'SOURCE public route first subscriber');
assert.equal(later,0,'SOURCE public route later subscriber cutoff');
assert.equal(error,origin,'SOURCE public route exact original cause');
process.stdout.write(JSON.stringify({last:store.tickers[0].last,first,later,message:error.message,code:error.code}));
