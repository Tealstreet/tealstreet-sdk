import fs from 'node:fs';
import path from 'node:path';
import {load,root,ts} from './source.mjs';
const relative='packages/safe-cex/src/exchanges/mexc/mexc.types.ts';
const api=load(relative);
const tables=Object.fromEntries(Object.entries(api).filter(([,v])=>typeof v !== 'function'));
const channels=['','rs.','rs.sub.ticker','rs.sub.kline','RS.sub.ticker','xrs.sub.ticker','push.ticker','pong','\uFEFFrs.login','rs.\n'];
const source=fs.readFileSync(path.join(root,relative),'utf8');
const ast=ts.createSourceFile(relative,source,ts.ScriptTarget.Latest,true);
const declaration=ast.statements.find(n=>ts.isTypeAliasDeclaration(n)&&n.name.text==='MexcEnvelope').getText(ast);
const shapes=[{}, {success:true},{success:false},{code:0},{code:'0'},{message:''},{msg:'x'},{data:null},{data:{nested:[1,null]}},{success:true,code:'200',message:'ok',msg:'yes',data:[1,2]},[],[true,0,'ok'],null,true,0,'x'];
for(const key of ['success','code','message','msg'])for(const value of [null,[],{},true,false,1,'ok'])shapes.push({[key]:value});
const testFile=path.join(root,'sdk-rs/safe-cex-venue-mexc/tests/__virtual_envelope.ts');
const body=declaration+'\n'+shapes.map((v,i)=>`const case_${i}: MexcEnvelope = ${JSON.stringify(v)};`).join('\n');
const options={strict:true,exactOptionalPropertyTypes:true,noEmit:true,target:ts.ScriptTarget.ES2022,skipLibCheck:true};
const host=ts.createCompilerHost(options),read=host.readFile.bind(host),exists=host.fileExists.bind(host);
host.readFile=file=>file===testFile?body:read(file);
host.fileExists=file=>file===testFile||exists(file);
const program=ts.createProgram([testFile],options,host),file=program.getSourceFile(testFile);
const diagnostics=ts.getPreEmitDiagnostics(program);
const globalErrors=diagnostics.filter(d=>!d.file||d.file.fileName!==testFile);
if(globalErrors.length)throw Error(ts.formatDiagnosticsWithColorAndContext(globalErrors,{getCurrentDirectory:()=>root,getCanonicalFileName:f=>f,getNewLine:()=> '\n'}));
const statements=file.statements.filter(ts.isVariableStatement);
const envelope=shapes.map((input,i)=>({input,accepted:!diagnostics.some(d=>d.start>=statements[i].pos&&d.start<statements[i].end)}));
process.stdout.write(JSON.stringify({tables,channels:channels.map(input=>({input,output:api.isMexcControlChannel(input)})),envelope}));
