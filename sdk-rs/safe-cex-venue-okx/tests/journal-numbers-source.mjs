import assert from 'node:assert/strict';
import {loadSource} from './source-loader.mjs';
const {mapOkxPositionHistory} = loadSource(new URL('../../../packages/safe-cex/src/journal/okx.position-adapter.ts',import.meta.url));
const row = {instId:'BTC-USDT-SWAP',closeTotalPos:'1e308',openMaxPos:'1e308',fee:'0',fundingFee:'0',realizedPnl:'0',openAvgPx:'100',uTime:'1000',cTime:'1',posSide:'long',type:'1'};
const deps = {account:'fixture',toBase:number=>number*2,resolveSymbol:()=> 'BTCUSDT',resolveSettleCurrency:()=> 'USDT'};
const record = mapOkxPositionHistory(row,deps);
assert.equal(record.closedSize,Infinity,'source computed closedSize');
assert.equal(record.maxSize,Infinity,'source computed maxSize');
assert.ok(Object.is(record.fees,-0),'source signed fee zero');
const nan = mapOkxPositionHistory({...row,closeTotalPos:'1',openMaxPos:'2'},{...deps,toBase:number=>number===1?1:NaN});
assert.ok(Number.isNaN(nan.maxSize),'source admitted callback NaN');
console.log('OKX JOURNAL native source numbers asserted before projection');
