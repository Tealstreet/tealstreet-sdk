const fs=require('fs'),path=require('path'),vm=require('vm'),assert=require('assert/strict');
assert.ok(process.env.SAFE_CEX_TYPESCRIPT_PATH, 'SAFE_CEX_TYPESCRIPT_PATH required');
const ts=require(process.env.SAFE_CEX_TYPESCRIPT_PATH);
const root=process.cwd(), file='sdk-rs/parity/extract-ts/src/extract.ts';
const moduleObject={exports:{}};
vm.runInNewContext(ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022,esModuleInterop:true}}).outputText,{module:moduleObject,exports:moduleObject.exports,require:n=>n==='typescript'?ts:require(n)});
const dir='packages/safe-cex/src/exchanges/paradex';
const files=fs.readdirSync(dir).filter(n=>n.endsWith('.ts')).map(n=>path.resolve(dir,n));
const program=ts.createProgram(files,{target:ts.ScriptTarget.ES2022,moduleResolution:ts.ModuleResolutionKind.Node10,esModuleInterop:true});
const result=files.map(file=>({ts:path.relative(root,file),symbols:moduleObject.exports.extractFile(program.getSourceFile(file),program.getTypeChecker(),path.resolve('packages/safe-cex'))}));
process.stdout.write(JSON.stringify(result));
