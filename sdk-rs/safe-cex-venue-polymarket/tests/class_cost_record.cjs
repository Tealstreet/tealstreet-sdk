const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const ts=require(process.env.SAFE_CEX_TYPESCRIPT_PATH);
const root=path.resolve(__dirname,'../../..');
const read=name=>{const text=fs.readFileSync(path.join(root,'packages/safe-cex/src/exchanges/polymarket',name),'utf8');return ts.createSourceFile(name,text,99,true);};
const types=read('polymarket.types.ts');
const shape=types.statements.find(n=>ts.isInterfaceDeclaration(n)&&n.name.text==='PolymarketOrderBookLevel');
assert(shape&&!shape.heritageClauses,'record direct declaration');
assert.deepEqual(shape.members.map(n=>[n.name.text,n.type.kind]),[['price',ts.SyntaxKind.StringKeyword],['size',ts.SyntaxKind.StringKeyword]],'record source schema');
const api=read('polymarket.api.ts');
const method=api.statements.find(n=>ts.isClassDeclaration(n)&&n.name.text==='PolymarketAPI').members.find(n=>n.name?.text==='getOrderBook');
const constants=read('polymarket.constants.ts');
const endpoints=constants.statements.find(n=>ts.isVariableStatement(n)&&n.declarationList.declarations.some(d=>d.name.getText(constants)==='ENDPOINTS'));
const context={exports:{}};
vm.runInNewContext(ts.transpileModule(endpoints.getText(constants)+`; class Selected { ${method.getText(api)} }; exports.Selected=Selected;`,{compilerOptions:{target:99,module:1}}).outputText,context);
const units=s=>Array.from({length:s.length},(_,i)=>s.charCodeAt(i));
(async()=>{const cases=[];for(let index=0;index<512;index++){
 const input={price:index%8===0?'':`price-😀-${index}`,size:`size-é-${512-index}`};
 const receiver=new context.exports.Selected();receiver.xhr={get:async()=>({data:{bids:[input],asks:[]}})};
 const actual=(await receiver.getOrderBook(`token-${index}`)).bids[0];
 assert.equal(typeof actual.price,'string');assert.equal(typeof actual.size,'string');
 cases.push({index,input,priceUnits:units(actual.price),sizeUnits:units(actual.size)});
}process.stdout.write(JSON.stringify({cases}));})().catch(e=>{console.error(e);process.exitCode=1;});
