const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm');
const assert = require('node:assert/strict');
const root = process.argv[2];
const ts = require(process.env.SAFE_CEX_TYPESCRIPT_PATH || path.join(root, 'node_modules/typescript'));
const file = path.join(root, 'packages/safe-cex/src/exchanges/woo/woo.exchange.ts');
const source = ts.createSourceFile(file, fs.readFileSync(file, 'utf8'), ts.ScriptTarget.Latest, true);
const owner = source.statements.find(node => ts.isClassDeclaration(node) && node.name?.text === 'WOOXExchange');
assert.ok(owner);
const members = owner.members.filter(node => node.name?.getText(source) === 'clientOrderIdRule');
assert.equal(members.length, 1);
const code = ts.transpileModule(`class Source { ${members[0].getText(source)} }; new Source().clientOrderIdRule;`, { compilerOptions: { target: ts.ScriptTarget.ES2022 }}).outputText;
const rule = vm.runInNewContext(code);
const ids = ['1', '12345', '100000000000000', '999999999999999', '9007199254740990', '9007199254740991', '9007199254740992', '9007199254740993', '9999999999999999999999999999999999999999', '1'.repeat(400), '0', '00', '01', '-1', '+1', '1.0', '1e3', '', ' 1', '1 ', 'NaN', 'Infinity', 'abc', '１', '١', '1_0'];
const rows = ids.map(input => ({ input, valid: rule.isValid(input) }));
assert.equal(rows.length, 26);
process.stdout.write(JSON.stringify({ label: rule.label, requirement: rule.requirement, rows }));
