const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const sdk = JSON.parse(fs.readFileSync(path.join(root, 'packages/safe-cex/package.json'), 'utf8'));
const target = process.argv[2];
assert(target && path.isAbsolute(target), 'provide an absolute worker dependency directory');
fs.mkdirSync(target, {recursive: true});
fs.writeFileSync(path.join(target, 'package.json'), JSON.stringify({private: true, packageManager: manifest.packageManager, dependencies: {lodash: sdk.dependencies.lodash}}, null, 2) + '\n');
fs.copyFileSync(path.join(root, 'yarn.lock'), path.join(target, 'yarn.lock'));
