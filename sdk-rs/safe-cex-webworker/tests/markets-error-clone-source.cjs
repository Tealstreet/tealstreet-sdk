const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const {isNativeError} = require('node:util').types;
const ts = require(process.env.SAFE_CEX_TYPESCRIPT_PATH || 'typescript');
const source = fs.readFileSync(path.resolve(__dirname,'../../../packages/safe-cex/src/webworker/handlers/BaseHandler.ts'),'utf8');
const js = ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS}}).outputText;
const timers = [], sent = [], cloned = [], moduleObject = {exports:{}};
vm.runInNewContext(js,{module:moduleObject,exports:moduleObject.exports,require(name){throw Error(`unexpected source import ${name}`);},console:{error(){}},setTimeout(callback,delay){timers.push({callback,delay});return timers.length;},clearTimeout(){}});
const handler = new moduleObject.exports.BaseHandler('account','bybit',{name:'bybit',store:{markets:[]}},{postMessage(message){sent.push(message);cloned.push(structuredClone(message));}},{},{});
assert.equal(handler.bufferUntilMarketsLoaded({op:'subscribeOHLCV',data:{symbol:'BTC',interval:'1m',subId:'s'}}),true);
const deadline = timers.find(timer=>timer.delay===30000);
assert(deadline,'MARKETS-ERROR source deadline registered'); deadline.callback();
assert.equal(sent.length,1); assert.equal(cloned.length,1);
const before = sent[0].data[1].sentryData.error, after = cloned[0].data[1].sentryData.error;
assert(isNativeError(before),'MARKETS-ERROR source constructs native Error');
assert.equal(before.name,'MarketsNotLoadedError');
assert(isNativeError(after),'MARKETS-ERROR structured clone retains Error identity');
assert.equal(after.name,'Error');
assert.equal(after.message,'Markets still not loaded after 30s, dropping 1 pending subscriptions');
assert.equal(typeof after.stack,'string'); assert(after.stack.length>0);
assert.equal(after.stack,before.stack);
const record={name:before.name,message:before.message};
assert(!isNativeError(structuredClone(record)),'MARKETS-ERROR JSON record cannot replace Error identity');
console.log('MARKETS-ERROR actual timeout: native Error before/after structured clone, original stack retained, custom name reset PASS');
