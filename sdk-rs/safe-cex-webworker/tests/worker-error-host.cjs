const assert = require('node:assert/strict');
const path = require('node:path');
const {isNativeError} = require('node:util').types;
assert(process.argv[2], 'provide the wasm-bindgen Node module path');
const wasm = require(path.resolve(process.argv[2]));
const sent = [], received = [];
wasm.post_timeout_error(payload => {
  sent.push(payload);
  received.push(structuredClone(payload));
});
assert.equal(sent.length, 1, 'WORKER-NATIVE-ERROR exactly one actual Wasm post');
assert.equal(received.length, 1);
const before = sent[0].data[1].sentryData.error;
const after = received[0].data[1].sentryData.error;
assert(isNativeError(before), 'WORKER-NATIVE-ERROR actual Wasm host creates native Error');
assert.equal(before.name, 'MarketsNotLoadedError');
assert(isNativeError(after), 'WORKER-NATIVE-ERROR clone retains native Error');
assert.notEqual(before, after, 'WORKER-NATIVE-ERROR receiving clone has new identity');
assert.equal(after.name, 'Error');
assert.equal(after.message, 'Markets still not loaded after 30s, dropping 1 pending subscriptions');
assert.equal(after.stack, before.stack, 'WORKER-NATIVE-ERROR original host stack survives');
assert.equal(typeof after.stack, 'string');
assert(after.stack.length > 0);
assert.equal(received[0].op, 'error');
assert.equal(received[0].data[0], after.message);
assert.equal(received[0].data[1].sendToSentry, true);
assert.deepEqual(received[0].data[1].sentryData.tags, {worker_error_family:'markets_not_loaded'});
assert.deepEqual(received[0].data[1].sentryData.extra, {pendingCount:1});
assert.throws(() => wasm.post_timeout_error(() => {throw new TypeError('post rejected');}), /post rejected/, 'WORKER-NATIVE-ERROR callback failure is visible');
console.log('WORKER-NATIVE-ERROR actual Wasm host: native Error, structured-clone stack/name/identity and post failure PASS');
