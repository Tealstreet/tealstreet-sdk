//! Private endpoints for the two Binance account types that share USD-M
//! public data: plain USD-M futures (`fapi`) and portfolio margin (`papi`).

pub struct Paths {
    pub rest: &'static str,
    pub rest_testnet: &'static str,
    pub private_ws: &'static str,
    pub private_ws_testnet: &'static str,
    /// Portfolio margin puts the listenKey in the path, USD-M in the query.
    pub listen_key_in_path: bool,
    pub listen_key: &'static str,
    pub leverage_bracket: &'static str,
    pub position_mode: &'static str,
    pub position_risk: &'static str,
    /// USD-M reads leverage and margin type here; portfolio margin's position
    /// rows carry leverage and it is cross only.
    pub symbol_config: Option<&'static str>,
    pub balance: &'static str,
    pub open_orders: &'static str,
    pub open_conditional_orders: &'static str,
    pub order: &'static str,
    pub batch_orders: Option<&'static str>,
    pub conditional_order: &'static str,
    pub cancel_all: &'static str,
    pub cancel_all_conditional: &'static str,
    pub leverage: &'static str,
    pub margin_type: Option<&'static str>,
    pub user_trades: &'static str,
    pub all_orders: &'static str,
    pub income: &'static str,
}

